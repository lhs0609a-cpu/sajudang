import { useState } from "react";
import Link from "next/link";
import { BIZ, BIZ_READY } from "@/lib/biz";
import Shell, { Legal } from "@/components/Shell";

const TABS = ["이용약관", "개인정보처리방침", "환불정책"] as const;
type Tab = (typeof TABS)[number];

export default function LegalPage() {
  const [tab, setTab] = useState<Tab>("이용약관");

  return (
    // 다른 화면과 같은 껍데기를 씁니다. 여기만 다르면 손님은 이 화면이
    // 우리 것이 아닌 줄 압니다 (tests/test_screen_beat.py 가 봅니다).
    <Shell title="알려 드리는 것">
      <div className="legalpg">

      <div className="ltabs">
        {TABS.map((t) => (
          <button
            key={t}
            className={"op" + (tab === t ? " on" : "")}
            onClick={() => setTab(t)}
          >
            {t}
          </button>
        ))}
      </div>

      {tab === "이용약관" && <Terms />}
      {tab === "개인정보처리방침" && <Privacy />}
      {tab === "환불정책" && <Refund />}

      <BizBlock />
      <Legal />

        <p className="back">
          <Link href="/">돌아가기</Link>
        </p>
      </div>
    </Shell>
  );
}

/* ── 사업자 표시 — 전자상거래법 제10조 ─────────────────── */
// ★ 페이지 파일에서는 default 말고 아무것도 내보내면 안 됩니다.
//   Next 라우터가 그 이름을 라우트 설정으로 읽어 빌드가 터집니다.
function BizBlock() {
  const rows: [string, string][] = [
    ["상호", BIZ.name],
    ["대표", BIZ.owner],
    ["사업자등록번호", BIZ.regNo],
    ["통신판매업 신고번호", BIZ.mailOrderNo],
    ["주소", BIZ.address],
    ["전화", BIZ.tel],
    ["전자우편", BIZ.email],
    ["개인정보 보호책임자", BIZ.privacyOfficer],
  ];
  return (
    <section className="biz">
      <h2>사업자 정보</h2>
      {!BIZ_READY && (
        <p className="warn">
          아직 다 채워지지 않았소. 채워지기 전에는 값을 받지 않소.
        </p>
      )}
      <dl>
        {rows.map(([k, v]) => (
          <div key={k}>
            <dt>{k}</dt>
            <dd>{v || <em>아직 없음</em>}</dd>
          </div>
        ))}
      </dl>
    </section>
  );
}

