"use client";

/*
 * 액트아웃 — 막을 끊는 한 줄.
 *
 * ★ 손님이 한 말 (2026-09-02)
 *
 *   "사주를 읽을 때마다 미드처럼 다음 화로 넘어가고 싶어 궁금해
 *   미치겠을 정도로. 모든 페이지가 다 그렇게 구성되어야 해.
 *   그렇지 않으면 실패야."
 *
 * ★ 미드가 하는 것
 *
 *   한 시간 드라마는 티저 + 4~5막입니다. 스트리밍은 광고가 없는데도
 *   같은 박자를 씁니다 — 광고 때문이 아니라 **사람이 그렇게 읽기
 *   때문**입니다. 막 끝은 반드시 다섯 중 하나로 끊습니다:
 *
 *       밝힘       여태 몰랐던 것이 여기서 드러난다
 *       뒤집기     알던 것이 틀렸다
 *       딜레마     둘 중 하나를 골라야 한다
 *       끊긴 동작  시작했는데 아직 안 끝났다
 *       남긴 물음  묻고 답을 안 한다
 *
 *   까닭은 자이가르닉 효과입니다 — 끝난 일보다 **안 끝난 일**이
 *   머리에 오래 남습니다.
 *
 * ★ 자동재생은 안 합니다
 *
 *   넷플릭스의 포스트플레이가 「계속 볼지」를 「그만 볼지」로
 *   뒤집었지만, 이 집은 하루 결제 2건 · 릴레이 2명 · 만류가 매출보다
 *   앞섭니다 (CLAUDE.md 절대 규칙 4). 밀지 않습니다 — 다음이
 *   **무엇인지 이름으로** 말할 뿐입니다. 고르는 건 손님입니다.
 *
 * ★ 자리가 고정입니다
 *
 *   본문 마지막(`closing_cut`)이 자리로 고정돼 있는 것과 같은
 *   까닭입니다 — 기억은 마지막이 지배합니다. 이 줄은 **버튼 바로
 *   위**에 옵니다. 여기 말고 다른 데 두지 마세요.
 *
 * ★ 지어내지 않습니다
 *
 *   여기 적는 것은 전부 **이미 참인 것**이라야 합니다. 「다음에 큰
 *   일이 있소」 같은 말은 이 집이 금지한 것입니다 (docs/11).
 *   「아직 안 한 말이 있소」 는 참입니다 — 실제로 안 했으니까요.
 */

export type ActKind = "밝힘" | "뒤집기" | "딜레마" | "끊긴 동작" | "남긴 물음";

export default function ActOut({
  kind,
  next,
  children,
}: {
  /** 다섯 꼴 중 무엇인가. 화면에는 안 보이고 자리만 잡습니다. */
  kind: ActKind;
  /**
   * 다음에 오는 것의 **이름**. 「더 있소」는 예고가 아닙니다 —
   * 이름을 불러야 궁금해집니다.
   */
  next?: string;
  children: React.ReactNode;
}) {
  return (
    <div className="actout noprint" data-kind={kind}>
      <p>{children}</p>
      {next && (
        <p className="nextname">
          다음 자리 — <b>「{next}」</b>
        </p>
      )}
    </div>
  );
}
