def valid(value):
    value=(value or '').upper()
    return value if re.fullmatch(r'[EI][SN][TF][JP]',value) else None


def build(f, value, concern):
    if concern == 'real_estate':
        concern = 'money'
    code=valid(value)
    if not code or concern not in TOPIC:return None
    title,question,action=TYPES[code]
    scene,distinction=TOPIC[concern]
    from .reading_precision import CASES
    case=CASES[concern]
    boundary='직접 고른 MBTI를 설명과 행동 방식에 참고했소. 사주로 성격 유형을 판정하거나 생년월일 계산을 바꾼 것은 아니오. 실제 모습과 다르면 경험을 먼저 두시오.'
