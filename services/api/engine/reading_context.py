def key(concern, rule):
    return f'reason:{concern}:{rule}'


def selected(plan):
    for claim in plan['selected']:
        value = plan['answers'].get(key(plan['concern'], claim['id']))
        if claim['answer'] in ('yes', 'mixed') and value in REASONS[claim['id']]:
            return claim, value, REASONS[claim['id']][value]
    return None


def pending(plan):
    return next((c for c in plan['selected'] if c['answer'] in ('yes', 'mixed')
                 and key(plan['concern'], c['id']) not in plan['answers']), None)
