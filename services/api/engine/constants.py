def element_of(char: str) -> str:
    """천간이든 지지든 오행을 돌려준다."""
    if char in ELEMENT_OF_GAN:
        return ELEMENT_OF_GAN[char]
    return ELEMENT_OF_JI[char]


def ten_god(gan: str, day_gan: str) -> str:
    """일간 대비 천간 하나의 십신. docs/05 §6"""
    e, me = ELEMENT_OF_GAN[gan], ELEMENT_OF_GAN[day_gan]
    same = YIN_YANG[gan] == YIN_YANG[day_gan]
    if e == me:
        return "비견" if same else "겁재"
    if GENERATES[me] == e:
        return "식신" if same else "상관"
    if CONTROLS[me] == e:
        return "편재" if same else "정재"
    if CONTROLS[e] == me:
        return "편관" if same else "정관"
    return "편인" if same else "정인"
