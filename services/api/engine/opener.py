def _age_band(f) -> str:
    age = int(f.age)
    if age < 30:
        return '이십대'
    if age < 40:
        return '삼십대'
    if age < 50:
        return '사십대'
    return '쉰넘어'


def _helper_band(f) -> str:
    seats = {s.get('pillar') for s in (f.helpers or []) if s.get('pillar')}
    n = len(seats)
    return '없음' if n == 0 else ('하나' if n == 1 else ('둘' if n == 2 else '셋넘어'))


def _pattern_band(f, concern: Optional[str]) -> str:
    from . import pattern as _pattern
    n = len(_pattern.read(f, concern, limit=99)) if concern else 0
    return '없음' if n == 0 else ('하나' if n == 1 else ('둘' if n == 2 else '셋넘어'))


def _daeun_group(f) -> str:
    from .topic import GROUP_OF
    return GROUP_OF.get(f.daeun_ten_god, f.daeun_ten_god)


def _prev_group(f) -> str:
    from .topic import GROUP_OF
    rows = list(f.daeun or [])
    i = int(f.daeun_now) - 1
    tg = (rows[i] or {}).get('ten_god') if 0 <= i < len(rows) else f.daeun_ten_god
    return GROUP_OF.get(tg, tg)


def _year_el(f) -> str:
    from .constants import ELEMENT_OF_GAN, HIDDEN
    ji = (f.pillars[0] or {}).get('ji') if f.pillars else ''
    hid = HIDDEN.get(ji) or []
    return ELEMENT_OF_GAN[hid[0][0]] if hid else f.strong_el


def _rarity_band(f) -> str:
    from . import rarity as _rarity
    try:
        return (_rarity.look(f) or {}).get('band') or '흔함'
    except Exception:
        return '흔함'


def _match_n(f, axis4) -> str:
    from .bank import axis_compare
    got = axis_compare(f, axis4)
    return str(len(got['matches'])) if got['usable'] else ''


def _gap_n(f, axis4) -> str:
    from .bank import axis_compare
    got = axis_compare(f, axis4)
    return str(len(got['gaps'])) if got['usable'] else ''


