def _key(f, cut_id: str, concern: Optional[str], axis4) -> str:
    if cut_id == 'spine' or cut_id == 'counter':
        return f.strength
    if cut_id == 'spine_depth':
        return f.top_ten_god
    if cut_id == 'place':
        return concern or ''
    if cut_id == 'spine_scene':
        return f.flow
    if cut_id == 'lens_bridge':
        return f.day_gan
    if cut_id == 'lack':
        return f.weak_el
    if cut_id == 'hope':
        return f.strong_el
    if cut_id == 'rarity':
        return _rarity_band(f)
    if cut_id == 'daeun_now':
        return _daeun_group(f)
    if cut_id == 'hindsight':
        return _prev_group(f)
    if cut_id == 'daeun_map':
        return _age_band(f)
    if cut_id == 'helper':
        return _helper_band(f)
    if cut_id == 'ancestor':
        return _year_el(f)
    if cut_id == 'concern_pattern':
        return _pattern_band(f, concern)
    if cut_id == 'concern_turn':
        from .portrait import _age_key
        return _age_key(f)
    if cut_id == 'axis':
        return _match_n(f, axis4)
    if cut_id == 'concern_face':
        return _gap_n(f, axis4)
    return ''


def line(f, cut_id: str, concern: Optional[str] = None, axis4=None) -> str:
    """이 컷의 사람 줄. 표에 없으면 **빈 글**이오 — 지어내지 않소."""
    if cut_id in SKIP or cut_id.startswith('lc_'):
        return ''
    table = SAY.get(cut_id)
    if not table:
        return ''
    try:
        key = _key(f, cut_id, concern, axis4)
    except Exception:
        return ''
    return table.get(key or '', '')


def apply(cuts: list, f, concern: Optional[str] = None, axis4=None,
          you: str = '그대', seen=None) -> list:
    """
    컷 목록의 머리마다 사람 줄을 얹는다.

    ★ 한 자리에서만 겁니다. 컷 스무 군데에 손으로 박으면 언젠가 한
      군데가 빠지고, 그 컷만 사전으로 열리오.
    """
    seen = seen if seen is not None else set()
    out = []
    for c in cuts:
        say = line(f, c.get('id') or '', concern, axis4)
        if say:
            said = voice.address(
                terms.gloss('<p class="op-you">%s</p>' % say, seen, concern,
                            getattr(f, 'sex', None)),
                escape(you))
            c = dict(c)
            c['html'] = said + c['html']
            c['opener'] = True
        out.append(c)
    return out
