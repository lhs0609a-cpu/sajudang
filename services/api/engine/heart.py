def solace(f, you: str, concern_word_: str, rarity: Optional[dict]) -> str:
    """
    위로 — 가장 아픈 말 바로 뒤.

    ★ 위로는 **면책**입니다. "괜찮다"가 아니라 "그건 그대 탓이 아니라
      구조다"를 셈으로 보이는 것입니다.
    """
    weak = f.weak_el
    does, force = LACK_DOES.get(weak, ("그 일", "그 힘"))
    band = (rarity or {}).get("band", "적잖음")
    say1, say2 = BAND_SAY.get(band, BAND_SAY["적잖음"])
    push = PUSH.get(f.strength, PUSH["중화"])
    face = TOP_FACE.get(f.top_ten_god, "쓰이고")
    n = 0
    for p in f.pillars:
        from .constants import ELEMENT_OF_GAN, ELEMENT_OF_JI
        if ELEMENT_OF_GAN.get(p["gan"]) == weak:
            n += 1
        if ELEMENT_OF_JI.get(p["ji"]) == weak:
            n += 1

    el = element_word(weak)
    how = ("하나도 없소" if n == 0
           else "%s뿐이오" % count_word(n))

    # ★ 조사를 손으로 박지 않습니다.
    #   「드러나는 일요」 「쇠이오」 가 그대로 나간 적이 있습니다.
    #   받침을 보고 답니다 (lens_cuts._fmt 와 같은 규칙).
    return (
        # ① 셈 — 손님이 세어 볼 수 있는 말로
        '<p class="tale">그대의 여덟 글자에서 %s %s. '
        '%s 하는 일은 <b>%s</b>.</p>'
        % (josa(el, "이", "가"), how, josa(el, "이", "가"),
           josa(does, "이오", "요"))
        # ② 없는 걸로 해 왔다 — 여기가 위로의 핵심
        + '<p class="tale">그러니 그대는 여태 <b>%s 가지지 못한 채 살아왔소.</b> '
          '안 한 것이 아니라, 남들은 타고나서 그냥 쓰는 것을 그대는 그때그때 '
          '애써 만들어 썼다는 말이오. 그 수고가 남 눈에 안 보였을 뿐이오.</p>'
          % josa(force, "을", "를")
        # ③ 면책 — 까닭은 셈에 있소
        + '<p class="tale">그것은 게을러서가 아니오. 그대의 힘은 %s. '
          '게다가 %s. 그러니 그 일은 늘 맨 뒤로 밀리오. '
          '<b>마음이 약해서가 아니라 여덟 글자가 그렇게 생겨서요.</b></p>'
          % (face, push)
        # ④ 희소도로 하는 위로 — 흔하면 혼자가 아니고, 드물면 당연하오
        + '<p class="bite">%s</p>' % say1
        + '<p class="tale">%s</p>' % say2
        # ⑤ 다만 위로로 덮지 않소
        + '<p class="sm">이 말로 %s 걱정이 사라지는 것은 아니오. '
          '다만 그대가 여태 힘들었던 것이 그대 성격 탓이 아니라는 것까지는 '
          '셈으로 말할 수 있소.</p>' % concern_word_
    )


# ══════════════════════════════════════════════════════════
# 희망 — **가진 것**으로 씁니다
# ══════════════════════════════════════════════════════════
#
# ★ 「좋아질 것이오」는 못 씁니다. 검증 불가능한 주장이고 시점 확정
#   금지에 걸립니다 (docs/11 · CLAUDE.md). 대신 이미 쥔 것을 셉니다 —
#   그건 손님이 만세력을 펴고 세어 볼 수 있는 말입니다.
# ★ 쉬운 말로 (2026-09-11). 「아닌 것을 가르는 자리」 는 무엇을 하는
#   힘인지 안 말했습니다. **살면서 언제 쓰이는지**로 적습니다.
# ★ 「…힘이오」 도 뜬 말이오 (2026-09-17). **무엇을 하는 재주인지**로
#   적습니다 — 「딱 잘라 끊는 힘」 보다 「아니라고 말하는 재주」 가
#   손님 눈에 그려지오.
STRONG_IS = {
    "목": ("없던 일을 시작하는 재주요", "아무도 안 하던 일을 처음 벌일 때 쓰이오"),
    "화": ("드러내 놓고 알리는 재주요", "사람들 앞에 나서서 알릴 때 쓰이오"),
    "토": ("가운데서 버텨 주는 재주요", "여럿이 갈릴 때 가운데를 지킬 때 쓰이오"),
    "금": ("아니라고 딱 잘라 말하는 재주요", "아닌 것을 가려내고 정리할 때 쓰이오"),
    "수": ("모아 두고 아껴 쓰는 재주요", "한발 물러나 생각하고 채울 때 쓰이오"),
}

YONG_GET = {
    "목": "새로 시작하는 일 하나를 곁에 두면",
    "화": "사람들 앞에 나서는 일 하나를 곁에 두면",
    "토": "받쳐 주는 사람 하나를 곁에 두면",
    "금": "정리하고 끊어 주는 사람 하나를 곁에 두면",
    "수": "혼자 쉬는 시간을 곁에 두면",
}


def hope(f, you: str, concern_word_: str, visible) -> str:
    """
    희망 — 때 뒤, 처방 앞.

    ★ 무엇이 생긴다고 말하지 않습니다. **가진 것**과 **바뀌는 때**만
      셉니다. 그 둘은 셀 수 있는 사실입니다.
    """
    strong = f.strong_el
    force, place = STRONG_IS.get(strong, ("그 힘이오", "그때그때 쓰이오"))
    n = visible(f, strong)
    el = element_word(strong)
    yong = element_word(f.yongsin) if f.yongsin else None
    get = YONG_GET.get(f.yongsin, "그것을 곁에 두면") if f.yongsin else None

    # 다음 칸까지 몇 해인가. **바뀌는 때만** 셉니다.
    nxt, left = None, None
    for d in (f.daeun or []):
        if int(d.get("start_age", 0)) > int(f.age):
            nxt = int(d["start_age"])
            left = nxt - int(f.age)
            break

    out = [
        # ① 가진 것 — 세어 볼 수 있는 말
        '<p class="tale">여태 없는 것만 셌으니, 이번에는 <b>있는 것</b>을 '
        '세겠소. 그대의 여덟 글자에서 가장 많은 것은 %s — %s. '
        '이것은 <b>%s</b>. 살면서는 %s.</p>'
        % (josa(el, "이오", "요"), count_word(n), force, place),
        # ② 그것이 값이오
        '<p class="bite">남들이 애써 만들어 쓰는 것을 그대는 처음부터 '
        '쥐고 태어났소.</p>',
        '<p class="tale">%s 문제에서 그대가 남보다 덜 애쓰고도 잘하는 것이 '
        '바로 이것이오. 여태 너무 당연해서 잘하는 것으로 안 쳤을 뿐이오. '
        '<b>타고난 것은 대개 제 것인 줄 모르오.</b></p>' % concern_word_,
    ]
    if yong and get:
        out.append(
            '<p class="tale">다만 많은 것만으로는 잘 안 돌아가오. %s '
            '있어야 그 힘이 제대로 쓰이는데, %s <b>%s</b> 살아나오.</p>'
            % (josa(yong, "이", "가"), get, josa(yong, "이", "가")))
    if nxt is not None:
        out.append(
            '<p class="tale">그리고 지금 대운이 끝까지 가는 것도 아니오. '
            '대운은 <b>%d년 뒤 %d살</b>에 바뀌오. 그때 무슨 일이 '
            '생긴다는 말이 아니오 — <b>바뀌는 때만 세는 것이오.</b> '
            '다만 지금 막힌 것이 영영 이대로는 아니라는 뜻이오.</p>'
            % (left, nxt))
    out.append(
        '<p class="sm">여기 적은 것은 다 여덟 글자에서 센 것이오. '
        '잘될 것이라는 말은 안 하오 — 그건 셈으로 알 수 없소.</p>')
    return "".join(out)


