def _visible(f, el: str) -> int:
    """
    겉에 보이는 개수. **`report._visible` 과 한 벌**입니다.

    ★ 여기서 다시 세지 않고 그 함수를 씁니다. 같은 것을 두 군데서 세면
      한쪽만 고쳐집니다. 모듈 맨 위에서 부르면 서로 물고 도니
      (report → heart → report) 부르는 자리에서 가져옵니다 — 그때는
      report 가 이미 다 올라와 있습니다.
    """
    from .report import _visible as v
    return v(f, el)


def solace(f, you: str, word: str, rr: dict) -> str:
    """
    가장 아픈 말 **바로 뒤**에 서는 자리. 아프게 해 놓고 그대로 다음
    진단으로 넘어가면 그건 진단서지 상담이 아닙니다.

    돌려주는 것은 문단 둘 — 셈에서 나온 위로 하나, 얇은 자리 하나.
    """
    band = BAND.get(rr.get("band"), BAND["적잖음"])
    words = rr.get("words", "")
    first = band.format(words=words,
                        wordsj=josa(words, "이오", "요"),
                        word=word, wordq=josa(word, "을", "를"))

    # ★ 무엇이 얇은지를 **먼저 이름으로** 답니다. 조각만 떨어뜨리면
    #   누구 얘긴지 안 적힌 사전 뜻풀이가 됩니다 (.\dev.ps1 subject).
    weak = f.weak_el
    lack = WEAK.get(weak, "").format(n=count_phrase(_visible(f, weak)) + ".")
    second = "여덟 글자에서 얇은 쪽은 %s. %s %s" % (
        josa(element_word(weak), "이오", "요"), lack,
        STRENGTH.get(f.strength, ""))

    return '<p class="tale">%s</p><p class="tale">%s</p>' % (
        first.strip(), second.strip())


def hope(f, you: str, word: str, visible) -> str:
    """
    처방 **앞**에 서는 자리. 「이걸 하시오」 앞에 「그대가 이미 쥔 것은
    이것이오」가 서야 처방이 숙제가 아니라 쓸 수 있는 힘이 됩니다.

    visible 은 `report._visible` — 겉에 보이는 개수를 세는 자리입니다.
    """
    strong, yong = f.strong_el, f.yongsin
    first = ("없는 것은 위에서 다 셌소. 이제 그대가 이미 쥔 것을 세오. "
             "여덟 글자에서 가장 두꺼운 쪽은 %s — 자리로 %s %s"
             % (
                josa(element_word(strong), "이오", "요"),
                count_phrase(visible(f, strong)) + ".",
                STRONG.get(strong, "")))

    n_yong = visible(f, yong) if yong else 0
    tmpl = YONGSIN_IN if n_yong else YONGSIN_OUT
    # ★ 조사는 손으로 안 답니다 — 「나무은」 「쇠은」 이 나옵니다.
    second = tmpl.format(
        el=josa(element_word(yong), "은", "는") if yong else "",
        n=count_phrase(n_yong) + ".")

    # ★ 바뀌는 나이는 셉니다. 그 나이에 무엇이 생긴다고는 말하지
    #   않습니다 — 때만 세는 것이 이 집의 규칙입니다.
    now = f.daeun[f.daeun_now]
    nxt = f.daeun[f.daeun_now + 1] if f.daeun_now + 1 < len(f.daeun) else None
    into = max(int(f.age) - int(now["start_age"]), 0)
    third = ("지금 %d살, %s 대운의 %d년째요. 이 판은 %d살에 바뀌오. "
             "%s 얘기를 접든 이어 가든 그 나이 안에서 셈하시오."
             % (int(f.age), now["gz"], into + 1,
                int(nxt["start_age"]) if nxt else int(now["start_age"]) + 10,
                word))

    return ('<p class="tale">%s</p><p class="tale">%s</p>'
            '<p class="tale">%s</p>' % (first, second, third))
