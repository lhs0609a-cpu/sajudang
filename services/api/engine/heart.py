def hold_line(cut_id: str, pick: int) -> str:
    """이 컷에 달 손잡이 한 줄. 없으면 빈 글자.

    pick   명식에서 뽑은 수. 사람마다 다른 줄이 나오게 합니다.
    """
    rows = HOLD_AT.get(cut_id)
    if not rows:
        return ""
    return '<p class="hold">%s</p>' % rows[pick % len(rows)]
