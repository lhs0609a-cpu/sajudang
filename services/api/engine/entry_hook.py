def _empty_ten_gods(f) -> list:
    return [k for k, v in f.ten_gods.items() if not v]


def _palace_now(f) -> Optional[dict]:
    """지금 나이가 앉은 궁위. 시각 미상이면 시주는 셈에서 뺍니다."""
    for p in f.palaces or ():
        if p.get("pillar") == "시주" and not f.hour_known:
            continue
        band = (p.get("age") or "").replace("세", "")
        try:
            if "~" not in band:
                continue
            lo, hi = band.split("~", 1)
            lo = int(lo)
            if hi.strip() == "":
                if f.age >= lo:
                    return p
                continue
            if lo <= f.age <= int(hi):
                return p
        except ValueError:
            continue
    return None


def _ledger(f) -> list:
    """장 0 — 세어 본 것. 셈만 적습니다."""
    top, n = f.top_ten_god, f.ten_gods[f.top_ten_god]
    empty = _empty_ten_gods(f)
    lines = ["여덟 글자를 세면 %s 가장 세오." % josa(top, "이", "가")
             if n <= 1 else
             "여덟 글자를 세면 %s %s." % (josa(top, "이", "가"),
                                    josa(count_word(n), "이오", "요"))]

    if empty:
        lines.append("열 가지 셈 가운데 %s 비었소 — %s 하나도 없소."
                     % (josa(count_word(len(empty)), "이", "가"),
                        josa(empty[0], "은", "는")))
    else:
        lines.append("열 가지 셈에 빈 칸이 없소. 골고루 든 자리요.")

    zero_el = [k for k, v in f.elements.items() if not v]
    if zero_el:
        lines.append("다섯 기운에서는 %s 아예 없소." % josa(zero_el[0], "이", "가"))
    else:
        lines.append("다섯 기운은 %s 가장 두텁고 %s 가장 얇소."
                     % (josa(f.strong_el, "이", "가"), josa(f.weak_el, "이", "가")))

    look = rarity_mod.look(f) or {}
    words = look.get("words")
    if words:
        lines.append("이렇게 놓인 자리는 %s." % josa(words, "이오", "요"))
        band = BAND_WORD.get(look.get("band"))
        if band:
            lines.append(band)
    return lines


def _ledger_source(f) -> str:
    empty = _empty_ten_gods(f)
    look = rarity_mod.look(f) or {}
    parts = ["십신 열 칸을 세었소 — %s %d · 빈 칸 %d."
             % (f.top_ten_god, f.ten_gods[f.top_ten_god], len(empty))]
    parts.append("다섯 기운은 " + " · ".join(
        "%s %s" % (k, ("%.1f" % v).rstrip("0").rstrip("."))
        for k, v in f.elements.items()) + "이오.")
    if look.get("count") and look.get("sample"):
        parts.append("희소도는 표본 %s명 가운데 %d명이오."
                     % (format(look["sample"], ","), look["count"]))
    return " ".join(parts)


def _turn(f) -> list:
    """장 3 — 언제 바뀌오. 나이만 셉니다. 사건은 안 적습니다."""
    lines = ["그대는 지금 %d살이오." % f.age]
    daeun = f.daeun or []
    now = f.daeun_now
    if 0 <= now < len(daeun):
        cur = daeun[now]
        lines.append("%d살에 여덟 글자를 읽는 기준이 한 번 바뀌었소." % cur["start_age"]
                     if f.daeun_started else
                     "%d살에 여덟 글자를 읽는 기준이 한 번 바뀌오." % cur["start_age"])
        if now + 1 < len(daeun):
            nxt = daeun[now + 1]["start_age"]
            lines.append("다음은 %d살이오. 앞으로 %d년 남았소."
                         % (nxt, max(nxt - f.age, 0)))
    palace = _palace_now(f)
    if palace:
        lines.append("지금 나이는 %s 자리(%s)에 앉아 있소."
                     % (palace["who"], palace["age"]))
    lines.append("그 해에 무슨 일이 생긴다고는 적지 않소. 바뀌는 때만 세오.")
    return lines


def _turn_source(f) -> str:
    daeun = f.daeun or []
    now = f.daeun_now
    parts = ["대운은 절입까지의 실제 일수로 세어 %s살부터 시작하오."
             % (daeun[0]["start_age"] if daeun else "—")] if daeun else []
    if 0 <= now < len(daeun):
        parts.append("지금은 %d번째 마디요 — %s · %s."
                     % (now + 1, daeun[now]["gz"], daeun[now]["ten_god"]))
    parts.append("궁위 나이 구간은 확정표를 그대로 쓰오 (docs/14 §6).")
    return " ".join(parts)


def _scene_source(f, strength: str) -> str:
    parts = ["대표로 잡힌 자리는 %s %d이오."
             % (f.top_ten_god, f.ten_gods[f.top_ten_god])]
    parts.append("전통 명리에서는 이를 %s으로 읽소." % strength)
    if f.top_ten_god_tied:
        parts.append("같은 비중의 자리가 하나 더 있소 — 이 장은 둘 가운데 하나로 읽은 것이오.")
    return " ".join(parts)


def build(f, concern: str, name: str = "", misses: int = 0) -> list:
    subject, question, action = CONCERNS[concern]
    group = TEN_GOD_GROUP[f.top_ten_god]
    scene, strength, boundary = SCENES[concern][group]
    hour_note = "" if f.hour_known else " 태어난 시간은 몰라 시주를 셈에서 뺐소."

    def chapter(stage, label, nav, paragraphs, source,
                mode="continue", next_label=""):
        return {
            "stage": stage, "label": label, "nav": nav,
            "source": escape(source + hour_note), "source_below": True,
            "html": "".join("<p>%s</p>" % escape(p) for p in paragraphs),
            "question": "최근 실제 경험과 가까운가요?",
            "yes": "그 자리를 기준으로 다음을 세겠소.",
            "no": "그 장면은 그대의 것으로 보지 않겠소. 다음은 셈만 대겠소.",
            "response_mode": mode,
            "next_label": next_label,
            "statement_id": "%s:%s:%s:%d:%s" % (
                VERSION, concern, f.top_ten_god, int(f.hour_known), stage),
        }

    greeting = "%s, " % name.strip() if name.strip() else ""

    # ★ 장면 장에도 **수를 댑니다** (2026-09-20).
    #
    #   처음 짤 때 셈은 0장에, 장면은 2장에 갈라 두었더니 장면 장이
    #   틀릴 수 있는 문장 5% 로 나왔습니다. 자를 고쳐 글에 맞출 뻔했는데,
    #   자를 글에 맞추면 그날로 자는 거울이 됩니다. 모자란 것은 자가
    #   아니라 글이었습니다 — 장면 옆에 그 장면이 **어느 셈에서 나왔는지**
    #   가 없었습니다. 손님이 만세력을 펴고 대 볼 수 있어야 합니다.
    top_n = f.ten_gods[f.top_ten_god]
    scene_lines = [
        greeting + scene,
        "지어낸 말이 아니오. 여덟 글자에서 %s %s, 그 자리를 %s 읽소."
        % (josa(f.top_ten_god, "이", "가"),
           josa(count_word(top_n), "이고", "고") if top_n else "없고",
           josa(strength, "으로", "로")),
        "%s 고민에서 갈리는 자리는 %s." % (subject, josa(boundary, "이오", "요")),
    ]
    # ★ 위로는 **아픈 말 뒤**이고, 셈에서 나옵니다 (engine/heart).
    #
    #   앞 판에는 진입부에 위로가 한 줄도 없었습니다. 장면으로 아프게
    #   해 놓고 그대로 처방으로 넘어가면 그건 상담이 아니라 진단서요.
    #   다만 **한 박자 늦춥니다** — 장면 바로 다음 줄에 붙이면 아픈 말이
    #   그 자리에서 무효가 됩니다. 셈과 축을 댄 뒤 맨 끝에 놓습니다.
    #
    #   흔하면 「혼자가 아니오」, 드물면 「이해받기 어려웠던 게 당연하오」.
    #   골라 담지 않고 재어 둔 등급을 그대로 씁니다.
    band = (rarity_mod.look(f) or {}).get("band")
    say = heart_mod.BAND_SAY.get(band)
    if say:
        scene_lines.append(say[1])

    # ★ 아니라고 한 손님에게는 **본 장을 고치지 않고 다음 장의 축을**
    #   바꿉니다 (2026-09-20).
    #
    #   이미 읽은 장면을 몰래 갈아 끼우면 손님은 자기가 무엇에 아니라고
    #   했는지 알 수 없습니다. 그렇다고 그대로 밀고 가면 그 순간 이게
    #   녹음이라는 걸 압니다. 그래서 **본 장은 그대로 두고, 뒤 두 장을**
    #   장면에서 셈으로 옮깁니다 — 셈은 아니라고 할 수 없는 자리요.
    turn_lines = _turn(f)
    if misses:
        turn_lines = ["앞 장면은 그대의 것이 아니라 했소. 그 말로 성격을 정하지 않겠소.",
                      "그러면 장면은 접고 셈만 대겠소."] + turn_lines
        act = ("%s 고민에서 그대가 실제로 한 선택 하나를 적어 보시오. "
               "무엇을 했는지와 왜 했는지를 따로 적으면 그 사이가 보이오." % subject)
        act_tail = "적어 놓고도 안 보이면 이 축은 접으시오. 셈은 남고 풀이는 갈아 끼우오."
    else:
        act = action
        act_tail = "적어 놓고 %s 보이는지만 보시오." % josa(boundary, "이", "가")

    chapters = [
        chapter("0", "여덟 글자에서 세어 본 것", "세어 본 것",
                _ledger(f), _ledger_source(f),
                next_label="이 셈이 어디서 드러나는지 읽기"),
        chapter("2", question, "그래서 이렇게",
                scene_lines, _scene_source(f, strength),
                mode="experience", next_label="이 자리가 언제 바뀌는지 읽기"),
        chapter("3", "이 자리가 언제 바뀌오", "언제 바뀌오",
                turn_lines, _turn_source(f),
                next_label="오늘 한 가지 읽기"),
        chapter("4", "오늘은 이 한 가지", "오늘 한 가지", [
            act,
            act_tail,
            "여기까지가 스무 사람 가운데 한 사람의 눈으로 센 것이오.",
        ], "처방은 물으신 자리(%s)에서 고르오. 셈이 아니라 고민이 정하는 자리요."
            % subject, next_label="첫 해석 정리하기"),
    ]

    # 어려운 말은 **그 자리에서** 풉니다 — 설명이 붙으면 어려운 말이
    # 아닙니다(국립국어원 2019). 훅 한 벌에서 한 번만 풉니다.
    seen: set = set()
    for c in chapters:
        c["html"] = terms_mod.gloss(c["html"], seen, concern, f.sex)
        c["source"] = terms_mod.gloss(c["source"], seen, concern, f.sex)
    return guard.enforce_deep(chapters)
