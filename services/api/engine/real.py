def of(axis: str, key: str) -> str:
    """이 축 값이 살림에서 무엇인가. 모르면 빈 문자열 — 지어내지 않는다."""
    return TABLES.get(axis, {}).get(key, "")


def add(axis: str, key: str, seen: Optional[set] = None) -> str:
    """
    붙일 한 줄. **한 장에 한 번**만.

    ★ 같은 축이 한 캐릭터의 컷 두셋에 걸립니다. 매번 같은 줄을
      붙이면 손님은 녹음인 줄 압니다.
    """
    txt = of(axis, key)
    if not txt:
        return ""
    tag = "%s:%s" % (axis, key)
    if seen is not None:
        if tag in seen:
            return ""
        seen.add(tag)
    return " " + txt
