def scene_of(table: str, key: str, concern: str) -> str:
    """이 칸의 살림 장면. 모르면 빈 글 — 지어내지 않습니다."""
    return ((TOPIC_TABLES.get(table, {}) or {}).get(key or "", {}) or {}).get(
        concern or "", "")


def scene_add(table: str, key: str, concern: str, seen=None) -> str:
    """붙일 한 줄. **한 장에 한 번**만 — 표와 칸이 같으면 두 번 안 냅니다."""
    txt = scene_of(table, key, concern)
    if not txt:
        return ""
    tag = "scene:%s:%s" % (table, key)
    if seen is not None:
        if tag in seen:
            return ""
        seen.add(tag)
    return txt
