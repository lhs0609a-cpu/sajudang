def build(plan, f):
    gods = plan['personal']['dominant_gods']
    contextual = reading_context.selected(plan)
    center = contextual[0] if contextual else next(iter(plan['selected']), None)
    evidence = list(center['evidence_ids']) if center else ['structure']
    evidence += ['group:' + TEN_GOD_GROUP[g] for g in gods]
    distribution = {g: plan['facts']['group:' + g]['value'] for g in ('비겁','식상','재성','관성','인성')}
    visibility = {g: ('exposed' if any(s['position'] == '천간' for s in plan['facts']['group:' + g]['seats'])
                      else 'rooted' if distribution[g] else 'hidden' if plan['facts']['group:' + g]['seats'] else 'absent')
                  for g in distribution}
    return {'center': center['id'] if center else None, 'gods': gods,
            'month_god': plan['personal']['month_god'], 'day_god': plan['personal']['day_god'],
            'strength': f.strength, 'hour_known': f.hour_known,
            'distribution': distribution, 'visibility': visibility,
            'context': contextual, 'evidence_ids': list(dict.fromkeys(evidence)),
            'source': 'self_report' if contextual else 'traditional_hypothesis',
            'mode': 'revised' if plan['rejected'] else 'contextual' if contextual else 'provisional'}


def opening_lines(spine):
    if spine['mode'] == 'revised':
        return ['그대가 아니라고 한 설명을 다른 말로 다시 붙이지는 않겠소. 남아 있는 근거와 실제 경험부터 이어 보오.']
    lines = []
    for god in spine['gods']:
        title, strength, cost = PROFILE[god]
        lines.extend([title + '을 먼저 읽겠소.', strength])
        if not spine['context'] or spine['context'][1] != 'required':
            lines.append(cost)
    if len(spine['gods']) > 1:
        lines.append('두 모습이 함께 잡혀 하나만 그대의 성격이라고 고르지는 않겠소.')
    month, day = spine['month_god'], spine['day_god']
    if month != day:
        lines.append('일을 대하는 모습과 가까운 사람 곁의 모습을 나누어 보겠소.')
        lines.append('일하는 자리에서는 ' + PROFILE[month][0] + '을, 가까운 생활에서는 ' + PROFILE[day][0] + '을 함께 읽소.')
    if spine['context']:
        lines.extend([spine['context'][2][1], spine['context'][2][3]])
    return lines


def domain_lines(spine, concern):
    if spine['mode'] == 'revised':
        return ['앞에서 맞지 않다고 한 이야기를 이 자리에 다시 붙이지 않겠소. 이 일에서 실제로 어려웠던 대목을 듣고 싶소.']
    rows = [SCENES[god][DOMAINS.index(concern)] for god in spine['gods']]
    lines = [line for row in rows for line in row[:2]]
    n, seen = spine['distribution'], spine['visibility']
    if concern == 'money':
        if seen['재성'] == 'hidden':
            lines.append('사주에서는 돈을 주고받는 표시가 안쪽에 있소. 만든 것을 건네는 일과 값을 정하는 일을 따로 살펴보겠소.')
        elif seen['재성'] == 'absent':
            lines.append('돈을 주고받는 표시가 뚜렷하지 않아 수입이나 재산을 단정하지 않겠소. 실제 돈의 흐름부터 확인해야 하오.')
        elif n['재성'] > n['식상']:
            lines.append('만드는 일보다 주고받는 일을 앞에 두어 읽는 배치요. 새 거래를 받기 전에 끝낼 여력이 있는지 함께 보오.')
        else:
            lines.append('만들어 낸 것과 돌아오는 몫을 함께 읽는 배치요. 실제로 쓴 시간과 받은 값을 나란히 볼 필요가 있소.')
    elif concern == 'work':
        if n['관성'] and n['식상']:
            lines.append('생각을 꺼내는 힘과 정해진 약속을 지키는 힘이 함께 잡히오. 좋은 의견을 실제로 받아들일 순서까지 보오.')
        elif not n['관성']:
            lines.append('사주만 보고 직장에 맞지 않는다고 고르지는 않겠소. 일의 범위와 평가 기준이 정해져 있는지 먼저 물어야 하오.')
    elif concern == 'love':
        lines.append('가까운 생활의 자리에서는 ' + PROFILE[spine['day_god']][0] + '도 함께 읽소.')
        if spine['day_god'] not in spine['gods']:
            lines.append('일할 때 편한 방식과 가까운 사람에게 바라는 방식이 꼭 같지는 않다는 뜻이오.')
    elif concern == 'people':
        if seen['비겁'] == 'exposed':
            lines.append('내 뜻을 앞에 내놓는 표시도 겉에 있소. 상대가 고를 여지를 남겼는지 함께 보오.')
        else:
            lines.append('내 뜻을 겉으로 내놓는 표시가 앞서지는 않소. 겉으로 조용했다고 생각까지 없었다고 읽지는 않겠소.')
    elif concern == 'dir' and spine['strength'] == '신약':
        lines.append('지금 계산에서는 도움받을 조건을 먼저 살피오. 한 번에 크게 바꾸기보다 도와줄 사람과 작은 시험부터 정하시오.')
    elif concern == 'health' and not spine['hour_known']:
        lines.append('태어난 시각이 없어 이 대목은 넓게만 읽소. 실제로 쉬는 시각과 맡은 일의 양이 더 필요하오.')
    # Only one action per domain, with the same primary story order on ties.
    lines.append('이 일이 지금 고민이라면 · ' + rows[0][2])
    return lines


