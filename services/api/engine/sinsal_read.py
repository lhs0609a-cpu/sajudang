def _stance(at: list, age: int) -> tuple:
    """
    이 자리가 그대에게 **지나온 것인가, 지금인가, 아직인가.**

    돌려주는 것: (때말, 그 자리 이름) 또는 (None, None)
    """
    best = None
    for p in at:
        if p in PALACE_AGE:
            lo, hi = PALACE_AGE[p]
            if best is None or lo < PALACE_AGE[best][0]:
                best = p
    if not best:
        return (None, None)
    lo, hi = PALACE_AGE[best]
    when = PALACE_WHEN[best]
    if age > hi:
        return ("<b>%s</b> 얘기라, 그대는 이미 <b>지나온 자리</b>요" % when, best)
    if age < lo:
        return ("<b>%s</b> 얘기라, 그대에게는 <b>아직 안 온 자리</b>요" % when, best)
    return ("<b>%s</b> 얘기라, 그대가 <b>지금 선 자리</b>요" % when, best)


