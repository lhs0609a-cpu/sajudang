def whose_line(f, sv: dict) -> str:
    """
    이 신살이 **누구 쪽에서** 오는가. 못 세면 빈 글.

    같은 천을귀인이라도 년주(조상)에 앉은 사람과 시주(아랫사람)에
    앉은 사람은 다른 말을 들어야 합니다. 그게 이 집이 신살을 읽는
    방식이오 (docs/14 §6).
    """
    from .constants import HIDDEN, TEN_GOD_GROUP
    from .features import ten_god

    at = [x for x in (sv.get("at") or []) if x in PALACE_AGE]
    if len(at) != 1:
        # 여러 기둥에 걸쳐 있으면 한쪽으로 몰아 말하지 않습니다.
        return ""
    pillar = at[0]
    ji = next((p["gz"][1] for p in f.pillars if p.get("label") == pillar), "")
    if not ji or ji not in HIDDEN:
        return ""
    grp = TEN_GOD_GROUP.get(ten_god(HIDDEN[ji][0][0], f.day_gan))
    if not grp:
        return ""
    tbl = WHOSE["길신" if sv.get("kind") == "길신" else "그밖"]
    say = tbl.get(grp)
    if not say:
        return ""
    return ('<p class="tale"><span class="evk">누구 쪽</span>'
            '%s 지지가 <b>%s</b>이라, %s</p>' % (pillar, grp, say))


def check_line(sv: dict) -> str:
    """대 볼 수 있는 한 줄. 없으면 빈 글."""
    t = CHECK.get(sv["key"])
    return ('<p class="bite">%s</p>' % t) if t else ""


def folded(off: list) -> str:
    """
    접어 둔 것 — **이름과 한 줄 뜻만.**

    ★ 지우지 않습니다. 여덟 중 셋만 폈다고 나머지 다섯을 없애면
      「내 신살이 몇 갠지」를 손님이 못 셉니다. 있다는 것과 무엇인지는
      말하고, **읽지는 않습니다.**
    """
    if not off:
        return ""
    names = " · ".join("<b>%s</b>" % s["name"] for s in off)
    # ★ 조사는 **마지막 이름**의 받침을 보고 답니다. 「화개이」 가
    #   그대로 나갔습니다 — 이 집이 여러 번 겪은 자리입니다.
    return ('<p class="sm">그 밖에 %s%s 붙어 있소. 물으신 자리에서 크게 '
            '보던 것이 아니라 여기서는 이름만 적어 두오 — 다른 자리를 '
            '물으시면 그때 펴겠소.</p>'
            % (names, josa(off[-1]["name"], "이", "가")[len(off[-1]["name"]):]))
