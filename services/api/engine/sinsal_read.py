def focus_of(concern: Optional[str]) -> set:
    return FOCUS.get(concern or "", set())


def split(sinsal: list, concern: Optional[str]) -> tuple:
    """
    (물은 자리에서 보는 것, 접어 둘 것).

    ★ 하나도 안 걸리면 **접지 않습니다.** 물은 자리에서 볼 것이 없다고
      여덟을 다 접으면 손님은 빈 컷을 받습니다. 그때는 전부 폅니다.
    """
    want = focus_of(concern)
    on = [s for s in sinsal if s["key"] in want]
    off = [s for s in sinsal if s["key"] not in want]
    if not on:
        return (sinsal, [])
    return (on, off)


def when_line(sv: dict, age: int) -> str:
    """궁위에 나이를 박은 한 줄. 못 박으면 빈 글."""
    say, _p = _stance(sv.get("at") or [], int(age))
    if not say:
        return ""
    return '<p class="tale">%s %s.</p>' % (josa(sv["name"], "은", "는"), say)


