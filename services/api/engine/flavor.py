def lc_figure(html: str, nth: int, pick: int) -> str:
    """관점 컷 앞 세 개에 그림을 단다. 이미 있으면 안 단다."""
    if nth >= len(LC_FIGURE) or not html:
        return html
    if _FIG_HAVE.search(re.sub(r"<[^>]+>", " ", html)):
        return html
    rows = LC_FIGURE[nth]
    return html + wrap_fig(rows[pick % len(rows)])
