# ★ 집이 재는 자와 **한 벌**이라야 합니다. 두 벌을 들고 있었더니
#   여기서는 「그림이 있다」 고 안 달았는데 자는 「그림이 없다」 고 적는
#   자리가 생겼습니다 (engine/dramaturgy.FIGURE 머리말).
_FIG_HAVE = D.FIGURE


def figure(html: str, cut_id: str, pick: int) -> str:
    """
    그림이 없는 공통 컷에 한 줄 단다.

    html   말투·호칭 층을 **아직 안 태운** 글 (부르는 쪽이 태웁니다)
    pick   명식에서 뽑은 수. 사람마다 다른 그림이 나오게 합니다.
    """
    rows = FIGURE_AT.get(cut_id)
    if not rows or not html:
        return html
    #
    # ★ 모자란 만큼 답니다 — 한 줄만 달던 자리 (2026-09-17)
    #
    #   자는 450자마다 하나를 요구하는데 여기서는 **늘 한 줄만**
    #   달았습니다. 그래서 천이백 자짜리 컷은 아무리 돌아도 그림
    #   하나에서 멈췄고, 손님은 「너무 다 추상적이야」 라고 했습니다.
    #
    #   다만 끝없이 달지는 않습니다. 셋을 넘기면 그건 그림이 아니라
    #   수수께끼 모음이 되오 — 두 줄까지만 보탭니다.
    need = _fig_short(html)
    if need <= 0:
        return html
    out = html
    for k in range(min(need, 2)):
        out += wrap_fig(rows[(pick + k) % len(rows)])
    return out


def _enough_fig(html: str) -> bool:
    """이 컷에 그림이 **길이만큼** 있는가.

    ★ 「이미 있으면 안 단다」 가 길이를 안 봤습니다 (2026-09-15).

      한 컷에 둘을 달면 글이 늘어진다는 말은 맞습니다. 그런데 그
      말이 **천 자짜리 컷에도** 그대로 걸려 있었습니다. 컷 가운데
      「셈이오」 가 한 번 묻혀 있으면 그 컷은 영영 그림 하나입니다.

      집이 재는 자는 **450자마다 하나**입니다(engine/dramaturgy 비유
      축). 그러니 안 다는 기준도 같은 자라야 합니다 — 안 그러면
      스물두 컷짜리 리포트가 아무리 잘 써도 비유 64 에서 멈춥니다.
      자와 글이 다른 자를 쓰면, 고쳐도 점수가 안 움직입니다.
    """
    return _fig_short(html) <= 0


def _fig_short(html: str) -> int:
    """이 컷에 그림이 **몇 줄 모자란가**.

    ★ 표지가 아니라 그림을 셉니다 (2026-09-17).

      전에는 `D.FIGURE`(표지)를 그대로 세었습니다. 그래서 컷 어딘가에
      「여럿이 같이 할 때」 의 「같이」 가 묻혀 있으면 집은 「그림이
      이미 있다」 고 판단해 **그림을 영영 안 달았습니다.** 자가 틀리면
      글이 안 고쳐지는 게 아니라, 고칠 기회가 막힙니다.
    """
    text = re.sub(r"<[^>]+>", " ", html or "")
    want = max(1, round(len(text) / 450.0))
    return want - D.figure_hits(text)


def wrap_fig(line: str) -> str:
    """
    비유를 **제 상자**에 담는다.

    ★ 전에는 맨몸으로 붙였습니다 — `html + " " + 그림`. `</p>` 뒤에
      붙은 이름 없는 글이라 문단도 상자도 아니어서, 화면에서는 앞
      문단에 그대로 이어 붙은 한 줄로 보였습니다. 비유는 한 걸음
      물러서서 다른 목소리로 말하는 자리인데 그게 안 보였습니다.

      덤으로 눈이 쉬는 자리가 하나 생깁니다 — 한 컷이 줄글로만
      스무 줄 이어지던 자리들이 여기서 갈립니다 (typo._BREAK).
    """
    return '<p class="fig">%s</p>' % (line or "").strip()


