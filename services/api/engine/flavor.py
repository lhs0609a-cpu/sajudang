# 마지막 문장을 찾는 자리 — 본문 문단만. 근거·비유·팩폭은 안 건드립니다.
_LAST_P = re.compile(r'(<p class="tale">)(.*?)(</p>)(?![\s\S]*<p class="tale">)',
                     re.S)
_TAGEND = re.compile(r"[.!?…]\s*$")


def ask_of(lens_id: str) -> str:
    """이 캐릭터가 묻는 말."""
    return ASK.get(lens_id, "")


def open_of(lens_id: str) -> str:
    """이 캐릭터가 말을 여는 버릇."""
    return OPEN.get(lens_id, "")


def ask(html: str, lens_id: str, seen: Optional[set] = None) -> str:
    """
    본문 **마지막 문장**에 그 캐릭터의 묻는 꼬리를 단다.

    ★ 한 리포트에 몇 번만 답니다.

      문장마다 물으면 버릇이 아니라 고장입니다. 그리고 손님은
      대답할 데가 없는 물음을 계속 받으면 짜증을 냅니다.
      `seen` 이 한 장에 붙은 수를 셉니다.
    """
    tail = ASK.get(lens_id, "")
    if not html or not tail:
        return html
    if seen is not None:
        # 한 장에 넷까지. 그 이상은 버릇이 아니라 말버릇 흉내입니다.
        if len(seen) >= 4:
            return html
    m = _LAST_P.search(html)
    if not m:
        return html
    body = m.group(2).rstrip()
    # 이미 묻고 있으면 두 번 안 묻습니다.
    if body.endswith("?") or not _TAGEND.search(re.sub(r"<[^>]+>", "", body)):
        return html
    if seen is not None:
        seen.add(len(seen))
    return html[:m.start(2)] + body + " " + tail + html[m.end(2):]


def lead(text: str, lens_id: str) -> str:
    """여는 말 앞에 들머리를 붙인다. 캐릭터의 첫 마디 결을 잇는다."""
    head = OPEN.get(lens_id, "")
    if not head or not text or text.startswith(head):
        return text
    return head + text

