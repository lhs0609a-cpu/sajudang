# 곁말을 다는 네 자리 — 공통 컷의 어디쯤인가
#
# ★ 「위로」를 더했습니다 (2026-09-07).
#
#   손님이 짚었습니다 — "희망도 주고 위로도 주고 웃기기도 하고
#   울리기도 하고." 그런데 스무 사람이 **같은 위로**를 하면 그건
#   위로가 아니라 안내문입니다. 삼거리 노파는 웃기고 연담은 울려야
#   합니다. 위로 컷 본문은 셈에서 나오니 한 벌로 두고, 온도만
#   여기서 스물로 갈라 답니다.
# ★ 여섯째 자리 — 신살 (2026-09-08).
#
#   `tools/same_audit.py` 로 재보니 **캐릭터 축**에서 신살 컷이
#   1,592자에 **92% 겹침 · 낭비 1,468자** — 단일 최대였습니다.
#   같은 명식을 두고 스무 사람이 신살을 **거의 같은 말로** 읽었습니다.
#   두 번째 목패를 사는 까닭이 「다른 눈으로 본다」인데 말입니다.
SIDE_AT = ("lack", "why", "closing_cut", "solace", "hope", "sinsal")


def side(html: str, lens_id: str, cut_id: str,
         you: Optional[str] = None) -> str:
    """
    공통 컷에 그 사람의 곁말을 단다.

    ★ 세 자리에만 답니다. 컷마다 달면 관점이 아니라 잔소리입니다.

    ★ 호칭 층을 태웁니다.

      곁말을 하오체·「그대」 로 적어 두었더니, 자네·아저씨를 쓰는
      캐릭터의 리포트에 「그대」 가 그대로 나갔습니다
      (tests/test_voice.py 가 잡았습니다). 어미는 각자 제 결로 이미
      적었으니 말투 층은 안 태우고, **부르는 말만** 갈아 끼웁니다.
    """
    if cut_id not in SIDE_AT:
        return html
    rows = SIDE.get(lens_id)
    if not rows:
        return html
    txt = rows[SIDE_AT.index(cut_id)]
    if not txt or not html:
        return html
    if you:
        from . import voice as _voice
        txt = _voice.address(txt, you)
    return html + '<p class="side">%s</p>' % txt


