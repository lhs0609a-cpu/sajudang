def hindsight(f, concern: str, concern_word_: str) -> Optional[str]:
    """
    지나온 자리 — **틀릴 수 있는 말을 먼저** 한다.

    돌려주는 것이 None 이면 낼 자리가 없다는 뜻입니다 (아직 첫 칸).
    ★ 없으면 안 냅니다. 억지로 채우지 않습니다.
    """
    daeun = list(f.daeun or [])
    now = int(f.daeun_now or 0)
    if not daeun or now >= len(daeun):
        return None
    if now <= 0:
        # ★ 아직 첫 칸이면 지나온 칸이 없습니다. 지어내지 않고,
        #   **지금 칸에 들어온 때부터 오늘까지**를 짚습니다. 이것도
        #   손님이 그 자리에서 대 볼 수 있는 구간입니다.
        past = daeun[0]
        a, b = int(past["start_age"]), int(f.age)
        if b <= a:
            return None
    else:
        past = daeun[now - 1]
        a, b = int(past["start_age"]), int(daeun[now]["start_age"])
    read, does = PAST_READ.get(past["ten_god"], ("도는 시간", "그렇게 읽는 때"))

    return (
        '<p class="tale">앞일부터 말하지 않겠소. 앞일은 지금 바로 '
        '맞춰 볼 수가 없으니, 맞는지 틀리는지 아무도 모르오. '
        '<b>지나온 시간부터 짚겠소.</b> 이건 그대가 지금 바로 맞춰 볼 수 '
        '있소.</p>'
        '<p class="tale">그대의 <b>%d살부터 %d살까지</b>는 대운에 %s 들어와 '
        '있던 때였소. 그때 대운 글자는 %s요. 이 시기는 <b>%s</b>으로 읽소 — '
        '%s요.</p>'
        % (a, b, josa(past["ten_god"], "이", "가"), past["gz"], read, does)
        # ★ 「십 년」이라 박지 않습니다. 첫 칸이면 구간이 짧습니다.
        + '<p class="bite">그 %s 해에 무슨 일이 있었는지는 내가 모르오. '
          '다만 <b>정말 그렇게 지나갔는지</b>는 그대가 아오.</p>'
          % _YEARS.get(b - a, str(b - a))
        + _asked_then(f, concern, concern_word_, past)
        + '<p class="tale">맞으면 아래 글도 믿어도 좋소. 안 맞으면 '
          '이 풀이는 흘려들으시오 — 틀릴 수 있는 말을 먼저 하는 것이 이 집의 방식이오. '
          '<b>틀리면 틀린 줄 알 수 있는 말이라야 근거요.</b></p>'
        + '<p class="sm">이 나이는 여덟 글자와 절입 시각으로 센 것이라, '
          '사주 달력인 만세력을 펴면 같은 수가 나오오. 다만 그때 무슨 일이 '
          '있었다고는 말하지 않소 — 그건 셈으로 알 수 없소.</p>'
    )


def _asked_then(f, concern: str, word: str, past: dict) -> str:
    """
    ★ 그 칸을 **물으신 자리에서** 읽습니다.

      고민이 바뀌면 보는 축이 바뀝니다 (docs/20). 지나온 칸도
      마찬가지라, 같은 십 년이라도 돈으로 볼 때와 사람으로 볼 때
      짚는 데가 다릅니다. 안 그러면 여섯 칸이 글자까지 같아집니다 —
      tests/test_concern_spread 가 그걸 셉니다.
    """
    grp = concern_group(concern, getattr(f, "sex", None))
    if not grp:
        return ""
    from .topic import GROUP_OF
    same = GROUP_OF.get(past["ten_god"]) == grp
    n = int(getattr(f, "ten_gods", {}).get(past["ten_god"], 0) or 0)
    # ★ 쉬운 말로 (2026-09-11). 「결이 다른 십 년」 「그 칸이 바로 그
    #   무리요」 는 손님이 무슨 뜻인지 몰랐습니다. **무엇이 주인공이었나**로.
    if same:
        return ('<p class="tale">그리고 %s 물으셨으니 더 짚을 것이 있소. '
                '%s 여덟 글자에서 <b>%s</b>으로 보는데, 그 열 해가 바로 '
                '대운에 %s 들어와 있던 때요. <b>물으신 일이 그때 이미 한 번 크게 '
                '움직였다</b>는 말이오. 여덟 글자에 %s %s 들었으니, 그 열 '
                '해에 크게 움직였을 게요.</p>'
                % (josa(word, "을", "를"), josa(word, "은", "는"), grp,
                   josa(grp, "이", "가"),
                   josa(past["ten_god"], "이", "가"), count_word(n)))
    return ('<p class="tale">그리고 %s 물으셨으니 이것도 보시오. '
            '%s 여덟 글자에서 <b>%s</b>으로 보는데, 그 열 해에는 대운에 %s 들어왔소. '
            # ★ 「조용했거나 … 밀리고 있었거나 둘 중 하나요」 는 어느 쪽이
            #   와도 맞는 말이라 근거가 못 됐습니다 (2026-09-11 · 평가).
            #   **한쪽으로만** 말하고, 틀리는 조건을 같이 적습니다.
            '<b>그 열 해에는 %s 뒤로 밀려 있었을 것이오</b> — 다른 것이 '
            '먼저 앞에 나와 있던 때라는 말이오. 그때 %s 크게 풀렸다면 '
            '내가 틀린 것이오.</p>'
            % (josa(word, "을", "를"), josa(word, "은", "는"), grp,
               josa(past["ten_god"], "이", "가"), josa(word, "이", "가"),
               josa(word, "이", "가")))


