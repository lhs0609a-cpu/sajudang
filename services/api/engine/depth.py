def _counter_count(f, concern: str, word: str) -> str:
    """
    ★ 반증 조건에는 **셀 수 있는 수**가 있어야 합니다.

      「안 맞을 수도 있소」 는 아무것도 금지하지 않아 어떤 관찰에서도
      살아남습니다 — 반증하겠다면서 반증 불가능한 말을 한 셈입니다.
      tests/test_falsifiable 이 이 컷을 잡았습니다.

      그래서 이 읽기가 선 **수**를 그대로 냅니다. 손님이 만세력을 펴고
      세어 보고 다르면 우리가 진 것입니다.
    """
    grp = concern_group(concern, getattr(f, "sex", None))
    if not grp:
        return ""
    gods = getattr(f, "ten_gods", {}) or {}
    from .topic import GROUP_OF
    n = sum(v for g, v in gods.items() if GROUP_OF.get(g) == grp)
    top_n = int(gods.get(f.top_ten_god, 0) or 0)
    return ('<p class="tale">센 수를 있는 대로 내놓겠소. %s 고민은 <b>%s</b>으로 '
            '보는데 그 글자가 %s, 앞장선다고 읽은 %s %s. 나이는 %d살로 '
            '셌소. <b>이 수가 다르면 이 글이 통째로 틀린 것이오.</b> '
            '만세력을 펴고 세어 보시오.</p>'
            % (word, grp, count_word(n), josa(f.top_ten_god, "이", "가"),
               count_word(top_n), int(f.age)))
