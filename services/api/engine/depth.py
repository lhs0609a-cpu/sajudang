def _count_mid(n: int) -> str:
    """
    문장 **한가운데** 들어가는 세는 꼴.

    ★ 끝맺는 꼴(`bank.count_phrase`)을 여기 쓰면 「셋이오 것으로」 라는
      비문이 되고, 말투 층은 문장 끝만 갈아 끼우므로 그 「…이오」가
      해요체 캐릭터에서도 하오체로 남습니다 (tests/test_voice 가 잡습니다).
    """
    return "하나도 없는" if n <= 0 else count_word(n) + "인"


def hindsight(f, concern: str, word: str) -> str:
    """
    지나온 대운 한 칸. **첫 판에 있는 사람에게는 안 냅니다** — 되짚을
    것이 없는데 되짚는 척하면 그게 맞히는 시늉입니다.
    """
    if not getattr(f, "daeun_started", True) or f.daeun_now < 1:
        return ""
    prev = f.daeun[f.daeun_now - 1]
    now = f.daeun[f.daeun_now]
    grp_prev = _bite.group_of(prev.get("ten_god", ""))
    grp_now = _bite.group_of(now.get("ten_god", ""))
    past = PAST.get(grp_prev)
    turn = TURN.get(grp_now)
    if not past or not turn:
        return ""

    return ('<p class="tale">%d살부터 %d살까지가 <b>%s</b> 대운이었소. '
            '%s</p>'
            '<p class="tale">%s %s 얘기를 그때 방식으로 셈하고 있으면 '
            '어긋나는 자리가 여기요.</p>'
            % (int(prev["start_age"]), int(now["start_age"]),
               prev["gz"], past, turn, word))


def counter(f, concern: str, word: str) -> str:
    """
    이 풀이를 뒤집는 조건 셋. 손님이 대 보고 접을 수 있어야 합니다.
    """
    grp = _bite.group_of(f.top_ten_god)
    asks = [COUNTER_TG.get(grp), COUNTER_ST.get(f.strength),
            COUNTER_WEAK.get(f.weak_el)]
    asks = [a for a in asks if a]

    items = "".join('<p class="tale">· %s</p>' % a for a in asks)
    return ('<p class="tale">여기까지는 <b>%s</b> %s 것을 축으로, 지금 '
            '%d살 자리에서 셈한 말이오. 이 풀이가 틀렸다면 <b>이런 것</b>이 '
            '보이오 — 세어 보시오.</p>'
            '%s'
            '<p class="tale">셋 가운데 둘이 그대 얘기라면 여기 적은 %s '
            '풀이는 접으시오. 접는 것도 셈이오 — 안 맞는 말을 붙들고 '
            '있는 것보다 낫소.</p>'
            % (josa(f.top_ten_god, "이", "가"),
               _count_mid(f.ten_gods.get(f.top_ten_god, 0)),
               int(f.age), items, word))
