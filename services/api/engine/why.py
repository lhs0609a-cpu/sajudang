def axis_line(seen: str, axis: str) -> str:
    """관점 컷의 근거 — 관측에 그 **축의 뜻**을 붙인다."""
    got = AXIS.get(axis)
    if not got:
        return seen
    why, school = got
    out = "%s — %s" % (seen, why)
    src = SCHOOL.get(school, "")
    return out + (" 〔%s〕" % src if src else "")


# 갈래 — 지어낸 인용 대신 **어디서 온 규칙인지**만 댑니다.
SCHOOL = {
    "십신": "자평 명리 · 십신",
    "강약": "자평 명리 · 신강약",
    "용신": "자평 명리 · 용신",
    "절기": "만세력 · 절기",
    "신살": "신살 · 유파 확정표(docs/14)",
    "": "자평 명리",
}


def rule_of(name: str) -> str:
    """이 이름의 이치 한 줄. 모르면 빈 문자열."""
    return TEN_GOD.get(name) or GROUP.get(name) or RULE.get(name, "")


def line(seen: str, rule_key: str = "", school: str = "") -> str:
    """
    근거 한 줄을 **관측 · 이치 · 출처** 로 짓는다.

        line("庚일간 · 나무가 거의 없음 · 식신", "식신", "십신")
        → "庚일간 · 나무가 거의 없음 · 식신
           — 식신은 그대가 내놓는 자리라, 만들고 먹는 복을 보오
           〔자평 명리 · 십신〕"

    ★ 이치를 모르면 **붙이지 않습니다.** 아무 규칙이나 갖다 붙이면
      그건 근거가 아니라 장식입니다.
    """
    why = rule_of(rule_key) if rule_key else ""
    out = seen
    if why:
        out += " — " + why
    src = SCHOOL.get(school or ("십신" if rule_key in TEN_GOD or
                                rule_key in GROUP else ""), "")
    if why and src:
        out += " 〔%s〕" % src
    return out
