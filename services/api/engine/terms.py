# 긴 말부터 봐야 합니다 — 「지장간」을 「지지」로 자르면 안 됩니다.
_ORDER = sorted(MEANING, key=len, reverse=True)
_TERMS = re.compile("|".join(re.escape(t) for t in _ORDER))
_TAGS = re.compile(r"<[^>]*>")

# 이미 괄호로 풀려 있으면 또 풀지 않습니다.
_ALREADY = re.compile(r"[(（]")


def used_here(text: str, term: str, start: int, end: int) -> bool:
    """이 자리의 글자가 **정말 그 용어인가** — 풀렸는지는 안 봅니다.

    ★ 자와 풀이가 다른 표를 보고 있었습니다 (2026-09-15).

      `engine/dramaturgy` 의 쉬움 축은 어려운 말을 제 벌로 찾았습니다 —
      앞 글자만 보는 성긴 자입니다. 그래서 훅에서 이 둘이 「안 풀린
      말」로 섰습니다:

          편재격 — 격국 이름 한 낱말인데 앞 두 글자만 떼어 셌습니다
          세운 벽 — 세우다의 활용형인데 歲運 으로 셌습니다

      둘 다 **여기가 이미 가르고 있는 자리**입니다(`NOT_BEFORE` ·
      `ONLY_PARTICLE`). 풀이는 옳게 안 풀었는데 자는 「안 풀었다」고
      적었으니, 고칠 데를 가리키는 게 아니라 고칠 수 없는 데를
      가리킨 것입니다. 표는 한 벌이라야 합니다.
    """
    return _ok(text, term, start, end, glossed_too=True)


def _ok(text: str, term: str, start: int, end: int,
        glossed_too: bool = False) -> bool:
    """이 자리에서 풀어도 되는가."""
    tail = text[end:end + 6]
    for bad in NOT_BEFORE.get(term, ()):
        if tail.startswith(bad):
            return False
    head = text[start - 1: start] if start else ""
    if head in NOT_AFTER.get(term, ()):
        return False
    # ★ 낱말 **안**에서는 안 풉니다 (2026-09-19).
    #
    #   한국말은 띄어쓰기로 낱말이 갈립니다. 그러니 앞 글자가 한글이면
    #   그건 낱말 한가운데요 — 「아껴지지」 「따지지」 「커지지」 의
    #   「지지」 는 어미이지 地支 가 아닙니다.
    #
    #   여태 NOT_AFTER 에 어간 끝 글자를 **손으로 적어** 막고 있었는데,
    #   새 문장을 쓸 때마다 구멍이 났습니다. 못 풀고 지나가는 것은
    #   풀이가 하나 빠지는 것이고, 낱말 안을 푸는 것은 **문장이
    #   깨지는 것**입니다. 둘 중에는 앞이 낫습니다.
    if term in WORD_START and _is_hangul(head):
        return False
    if term in ONLY_PARTICLE:
        # 조사가 붙었거나, 뒤가 한글이 아닐 때(갑자 한자)만 용어입니다.
        nxt = tail.lstrip()[:1]
        if not (_PARTICLE.match(tail) or (nxt and not _is_hangul(nxt))):
            return False
    # 바로 뒤가 여는 괄호면 이미 풀린 것입니다. 「쓰였는가」를 묻는
    # 자리(used_here)는 풀렸어도 쓰인 것이라 이 칸을 안 봅니다.
    return True if glossed_too else not _ALREADY.match(tail[:1])


def _is_hangul(ch: str) -> bool:
    return "가" <= ch <= "힣"


def _piece(text: str, seen: Set[str], mean: dict) -> str:
    out, last = [], 0
    for m in _TERMS.finditer(text):
        term = m.group(0)
        if term in seen or not _ok(text, term, m.start(), m.end()):
            continue
        seen.add(term)
        out.append(text[last:m.start()])
        # ★ 괄호를 **글에 직접** 넣습니다. CSS 의 ::before 로만 두면
        #   태그를 걷어낸 자리에서 「용신모자란 것을 채워 줄 기운」처럼
        #   붙어 버립니다 — 공유 payload · 분석지 · 미리보기가 그렇습니다.
        out.append("%s<i class=\"gl\">(%s)</i>"
                   % (term, mean.get(term) or MEANING[term]))
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def gloss(html: str, seen: Optional[Set[str]] = None,
          concern: Optional[str] = None, sex: Optional[str] = None) -> str:
    """
    렌더된 HTML 에서 어려운 말을 **처음 한 번** 풀어 준다.

    seen 을 넘기면 그 묶음(리포트 한 장·훅 한 벌) 안에서 한 번만 풉니다.
    안 넘기면 이 덩이 안에서 한 번입니다.

    concern·sex 를 넘기면 **물으신 자리에 맞는 풀이**로 냅니다
    (MEANING_AT — 사랑을 물은 사내에게 재성은 「짝을 보는 자리」).

    ★ 태그 안은 건드리지 않습니다. 속성값에 손대면 화면이 깨집니다.
    """
    if not html:
        return html
    if seen is None:
        seen = set()
    mean = _at(MEANING_AT, concern, sex)
    out, last = [], 0
    for m in _TAGS.finditer(html):
        out.append(_piece(html[last:m.start()], seen, mean))
        out.append(m.group(0))
        last = m.end()
    out.append(_piece(html[last:], seen, mean))
    return "".join(out)

