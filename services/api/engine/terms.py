def ganji_picture(gz: str) -> str:
    """
    갑자 두 글자를 사람 말로. 「庚戌」 → 「벼려진 쇠가 늦가을 마른 흙 위에…」

    ★ 못 읽는 글자면 빈 문자열을 냅니다 — 지어내지 않습니다.
    """
    if not gz or len(gz) < 2:
        return ""
    g, j = GAN_PIC.get(gz[0]), JI_PIC.get(gz[1])
    if not g or not j:
        return ""
    # 조사는 **읽는 소리**로 고릅니다 — 戌은 '술' 이라 「庚戌은」
    from .constants import JI_SOUND
    sound = JI_SOUND.get(gz[1], "")
    eun = "은" if (sound and _has_batchim_ko(sound[-1])) else "는"
    return ("<b>%s</b>%s <b>%s</b>가 <b>%s</b> 위에 놓인 모습이오. "
            "%s. 아랫글자는 %s." % (gz, eun, g[0], j[0], g[1], j[1]))


def _has_batchim_ko(ch: str) -> bool:
    o = ord(ch)
    return 0xAC00 <= o <= 0xD7A3 and (o - 0xAC00) % 28 != 0


def picture_of(term):
    """이 말의 비유 한 줄. 없으면 빈 문자열."""
    return PICTURE.get(term, "")


def picture_box(terms, concern: Optional[str] = None,
                sex: Optional[str] = None):
    """
    이 컷에서 **처음 나온** 말들의 비유를 한 상자로 묶는다.

    ★ 컷 밑에 붙입니다. 리포트 끝에 몰아 두면 손님이 읽던 자리에서
      멀어져 안 봅니다 — 모르는 말을 만난 그 자리에 있어야 합니다.

    concern·sex 를 넘기면 **물으신 자리 쪽 비유**로 냅니다. 괄호 풀이와
    같은 층이라야 합니다 — 한쪽만 갈면 「짝을 보는 자리」라 풀어 놓고
    비유는 「달마다 꼬박꼬박 들어오는 삯」이 됩니다.
    """
    pic = _at(PICTURE_AT, concern, sex)
    rows = [(t, pic.get(t) or PICTURE[t]) for t in terms
            if pic.get(t) or PICTURE.get(t)]
    if not rows:
        return ""
    rows.sort(key=lambda r: _ORDER.index(r[0]) if r[0] in _ORDER else 999)
    inner = "".join('<p><b>%s</b> %s</p>' % (t, p) for t, p in rows)
    # ★ 상자 제목은 **말이 아니라 표지판**입니다 (2026-09-03).
    #
    #   「이게 무슨 말이오」 라고 적혀 있었습니다. 이 상자는 말투를
    #   갈아 끼우는 층을 타므로, 해요체 캐릭터에게서 「이게 무슨
    #   말이네요」 라는 **비문**이 나왔습니다. 손님이 그걸 보고 멈췄습니다.
    #   버튼·표지판을 손님 말투로 적지 않는 것과 같은 까닭으로,
    #   여기는 어느 말투에도 안 걸리는 꼴로 둡니다.
    return '<div class="gls"><em>이게 무슨 말인가</em>%s</div>' % inner
