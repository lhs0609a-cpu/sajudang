# ★ 같은 글자인데 다른 말인 자리 — 풀면 문장이 망가집니다.
#
#   「상관없소」 를 「상관(밖으로 내지르는 힘)없소」 로 만들면 안 됩니다.
#   「인성이 좋다」 도 십신의 인성이 아닙니다.
#   한 글자 차이로 뜻이 뒤집히는 자리라 뒤 글자를 봅니다.
NOT_BEFORE = {
    "상관": ("없", "하", "있", "치"),
    "인성": ("이 좋", "이 나쁘"),
    "정관": ("사",),          # 정관사
    "지지": ("하", "받", "층"),  # 지지하다 · 지지받다
}

# ★ 앞 글자를 봐야 하는 자리.
#   「격」은 한 글자라 성격·가격·자격·합격·인격에 다 걸립니다.
#   청암거사는 이걸 진짜 용어로 쓰므로(격국) 빼 버릴 수도 없습니다.
#   앞 글자로 가릅니다.
NOT_AFTER = {
    "격": ("성", "가", "자", "합", "인", "체", "규", "파", "승",
           "실", "엄", "품", "본", "저", "고", "동", "간", "적"),
}

# 긴 말부터 봐야 합니다 — 「지장간」을 「지지」로 자르면 안 됩니다.
_ORDER = sorted(MEANING, key=len, reverse=True)
_TERMS = re.compile("|".join(re.escape(t) for t in _ORDER))
_TAGS = re.compile(r"<[^>]*>")

# 이미 괄호로 풀려 있으면 또 풀지 않습니다.
_ALREADY = re.compile(r"[(（]")


def _ok(text: str, term: str, start: int, end: int) -> bool:
    """이 자리에서 풀어도 되는가."""
    tail = text[end:end + 6]
    for bad in NOT_BEFORE.get(term, ()):
        if tail.startswith(bad):
            return False
    head = text[start - 1: start] if start else ""
    if head in NOT_AFTER.get(term, ()):
        return False
    # 바로 뒤가 여는 괄호면 이미 풀린 것입니다
    return not _ALREADY.match(tail[:1])


def _piece(text: str, seen: Set[str]) -> str:
    out, last = [], 0
    for m in _TERMS.finditer(text):
        term = m.group(0)
        if term in seen or not _ok(text, term, m.start(), m.end()):
            continue
        seen.add(term)
        out.append(text[last:m.start()])
        # ★ 괄호를 **글에 직접** 넣습니다. CSS 의 ::before 로만 두면
        #   태그를 걷어낸 자리에서 「용신모자란 것을 채워 줄 기운」처럼
        #   붙어 버립니다 — 공유 payload · 분석지 · 미리보기가 그렇습니다.
        out.append("%s<i class=\"gl\">(%s)</i>" % (term, MEANING[term]))
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def gloss(html: str, seen: Optional[Set[str]] = None) -> str:
    """
    렌더된 HTML 에서 어려운 말을 **처음 한 번** 풀어 준다.

    seen 을 넘기면 그 묶음(리포트 한 장·훅 한 벌) 안에서 한 번만 풉니다.
    안 넘기면 이 덩이 안에서 한 번입니다.

    ★ 태그 안은 건드리지 않습니다. 속성값에 손대면 화면이 깨집니다.
    """
    if not html:
        return html
    if seen is None:
        seen = set()
    out, last = [], 0
    for m in _TAGS.finditer(html):
        out.append(_piece(html[last:m.start()], seen))
        out.append(m.group(0))
        last = m.end()
    out.append(_piece(html[last:], seen))
    return "".join(out)
