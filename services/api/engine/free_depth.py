def depth_html(flow):
    row = FLOW.get(flow)
    if not row:
        return ''
    title, scene, meaning, edge, comfort = row
    return ('<div class="free-depth-essay"><h3>%s</h3>'
            '<p>%s</p><p>%s</p><p><strong>%s</strong></p><p>%s</p>'
            '<p class="note">닮은 장면이 있을 때만 경험과 맞춰보시오. '
            '이 장면을 실제로 겪었다고 단정하는 것은 아니오.</p></div>') % tuple(
                escape(x) for x in (title, scene, meaning, edge, comfort))


def scene_html(concern, flow=None):
    row = CONCERNS.get(concern)
    if not row:
        return ''
    from .reading_workbook import scene_extension
    return ('<div class="free-depth-essay"><h3>%s</h3><p>%s</p><p>%s</p><p>%s</p></div>' % tuple(escape(x) for x in row)
            + scene_extension(concern, flow))
