def render(lens_id, concern, features, topic=None):
    from .editorial import ROLES, CONCERNS
    from .editorial_questions import question
    from .lens_cuts import _counted
    row = METHODS.get(lens_id)
    if row is None or concern not in CONCERNS:
        return ''
    axis, perspective, _, _ = ROLES[lens_id]
    _, scene, record = CONCERNS[concern]
    evidence = _counted(features, [axis])
    headings = ('먼저 짚을 핵심', '선택이 갈리는 기준', '실제로 꺼내 볼 말', '이 해석을 고쳐 읽어야 할 때')
    parts = ['<div class="consultation-method"><h3>%s</h3>' % escape(perspective),
             '<p class="note">명식에서 확인한 것 · %s</p>' % escape(evidence),
             '<p>이 계산을 바탕으로 살펴볼 질문이오. %s</p>' % escape(question(lens_id, concern))]
    for heading, text in zip(headings, row):
        parts.append('<h4>%s</h4><p>%s</p>' % (heading, escape(text)))
    if topic and topic.get('choice4') and topic.get('choice5'):
        from . import character_consultation
        from . import lens
        parts.append(character_consultation.render(
            lens_id, topic, name=lens.public(lens_id)['name']))
    parts.append('<h4>그대의 답으로 마무리하시오</h4><p>%s 하나를 골라 %s을 적으시오. '
                 '위 기준에서 맞는 대목 하나와 다른 대목 하나를 표시하시오. '
                 '다음에 같은 장면이 오면 바꿀 행동 하나를 정하고, 해본 뒤 실제로 달라진 점을 기록하시오. '
                 '해석을 외우는 것보다 내 선택의 근거를 남기는 것이 이 자리의 쓰임이오.</p></div>'
                 % (escape(scene), escape(record)))
    return ''.join(parts)


