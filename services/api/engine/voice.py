"""
말투 — 캐릭터마다 다른 목소리.

★ 여기가 통째로 없었습니다.
  `docs/07_캐릭터_20인_설정집.md` 은 스무 명의 말투를 이미 정해 놓았습니다 —
  은별 무녀는 "…어긋나네요", 홍매파는 "됐고, 생년월일이나 대봐",
  훈장은 "재주는 있다. 헌데 잘못 골랐어", 삼거리 노파는 "딴 데 가서 듣게",
  연담·화경은 "…보겠습니다", 청동자는 "괜찮아요. 진짜로요".

  그런데 **엔진이 그걸 무시하고 전부 하오체로 통일해** 버렸습니다.
  재보니 스무 명 중 **열여섯이 똑같이 "그대"** 라고 부르고, 어미도
  전부 `~오/~소` 한 결이었습니다. 관점은 스무 개 다 다른데(여는 말
  20/20) 목소리가 하나라, 두 사람을 이어 읽으면 중앙값 56%가 글자
  그대로 같은 글로 읽혔습니다.

★ 문장 뱅크를 스무 벌로 다시 쓰지 않습니다.
  뱅크는 하오체 한 벌로 두고, **맨 끝에서 어미만 바꿔 끼웁니다.**
  그러면 공통 컷(리포트의 60~90%)까지 그 사람 목소리로 나갑니다.

★ 지어내지 않습니다 — 불규칙 활용을 건드리지 않습니다.
  「쉽소 → 쉬워요」(ㅂ불규칙), 「그렇소 → 그래요」(ㅎ불규칙),
  「다르오 → 달라요」(르불규칙) 같은 것은 어간을 바꿔야 합니다.
  그런 변환은 한 글자만 틀려도 문장이 깨집니다.

  그래서 **어간을 그대로 두고 붙이기만 하면 되는 어미**로만 짰습니다:

      하오체   있소   · 하오    ← 뱅크 원문 (기본)
      합쇼체   있습니다 · 합니다   받침 있으면 -습니다 / 없으면 -ㅂ니다
      하게체   있네   · 하네    어간 + 네
      반말     있지   · 하지    어간 + 지
      해요체   있네요  · 하네요   어간 + 네요

  다섯 다 어간을 안 건드립니다. 「쉽소」는 「쉽습니다·쉽네·쉽지·쉽네요」가
  되고, 하나도 안 깨집니다. 못 다루는 꼴은 **그대로 둡니다** —
  하오체로 남는 것이 틀린 문장이 되는 것보다 낫습니다.
"""
from __future__ import annotations

import re
from typing import Optional

# ══════════════════════════════════════════════════════════
# 말투 다섯
# ══════════════════════════════════════════════════════════
HAO = "hao"          # 하오체 — 뱅크 원문 그대로
HAPSYO = "hapsyo"    # 합쇼체 — 정중
HAGE = "hage"        # 하게체 — 손윗사람이 아랫사람에게
BANMAL = "banmal"    # 반말 — 툭 던지는
HAEYO = "haeyo"      # 해요체 — 다정·친근

VOICES = (HAO, HAPSYO, HAGE, BANMAL, HAEYO)


# ══════════════════════════════════════════════════════════
# 한글 받침 보기
# ══════════════════════════════════════════════════════════
_BASE = 0xAC00
_LAST = 0xD7A3
_JONG = 28


def _has_batchim(ch: str) -> Optional[bool]:
    """받침이 있는가. 한글이 아니면 None."""
    if not ch:
        return None
    o = ord(ch)
    if not (_BASE <= o <= _LAST):
        return None
    return (o - _BASE) % _JONG != 0


# ══════════════════════════════════════════════════════════
# 해요체·반말의 아/어 — 「네요」 한 결로만 나가지 않게
# ══════════════════════════════════════════════════════════
#
# ★ 여덟 문장이 잇달아 「네요」 였습니다 (2026-09-03).
#
#     없네요 · 것이네요 · 후회했네요 · 남지 않았네요 · 안 내네요
#
#   「네요」 는 알아채는 말이라 한 번 쓰면 살고 여덟 번 쓰면 기계입니다.
#   손님이 여기서 멈췄습니다. 해요체의 본디 어미는 **아요/어요** 입니다.
#
# ★ 그래도 어간은 안 건드립니다.
#   아/어를 붙이는 자리에 불규칙이 몰려 있습니다 —
#       쉽소→쉬워요(ㅂ) · 듣소→들어요(ㄷ) · 낫소→나아요(ㅅ)
#       그렇소→그래요(ㅎ) · 다르오→달라요(르)
#   그래서 **받침이 ㅂ·ㄷ·ㅅ·ㅎ 이면 물러섭니다.** 받침이 없는 어간도
#   줄어들며 모음이 바뀌므로(보→봐, 주→줘) 물러섭니다. 물러선 자리는
#   「네요」 로 남습니다 — 하나가 어색한 것이 열이 똑같은 것보다 낫습니다.
#
#   다만 「하」 와 「되」 는 어느 낱말에서나 한 가지로만 줄어듭니다.
#   이 둘은 뱅크에서 가장 잦은 어간이라 표로 답니다.
_IRREGULAR_JONG = {7, 17, 19, 27}      # ㄷ · ㅂ · ㅅ · ㅎ
_BRIGHT_JUNG = {0, 2, 8, 12}           # ㅏ ㅑ ㅗ ㅛ
_JONG_SS = 20                          # ㅆ — 았/었/했/있. 언제나 '어'
_CONTRACT = {"하": ("해요", "해"), "되": ("돼요", "돼")}


def _a_eo(stem: str) -> Optional[str]:
    """어간에 붙일 '아' 나 '어'. 불규칙이 걸리면 None (물러선다)."""
    if not stem:
        return None
    o = ord(stem[-1])
    if not (_BASE <= o <= _LAST):
        return None
    jong = (o - _BASE) % _JONG
    if jong == 0 or jong in _IRREGULAR_JONG:
        return None
    if jong == _JONG_SS:
        return "어"
    jung = ((o - _BASE) // _JONG) % 21
    return "아" if jung in _BRIGHT_JUNG else "어"


def _drop_riul(ch: str) -> Optional[str]:
    """
    ㄹ 받침을 뗀다. 살 → 사 · 들 → 드 · 힘들 의 '들' → 드

    ★ ㄹ탈락은 **불규칙이 아니라 규칙**입니다.
      ㄹ 받침 어간은 -ㅂ니다 · -네 앞에서 언제나 ㄹ을 버립니다 —
      살다→삽니다·사네, 들다→듭니다·드네, 만들다→만듭니다·만드네.
      예외가 없어서 어간을 지어내는 것이 아닙니다.

      이걸 안 하면 「살습니다 · 살네」 가 나옵니다. 하오체로 「…ㄹ소」
      라고 쓴 자리가 합쇼체·하게체 캐릭터에서 통째로 비문이 됩니다.
    """
    o = ord(ch)
    if not (_BASE <= o <= _LAST) or (o - _BASE) % _JONG != 8:
        return None
    return chr(o - 8)


def _add_bieup(ch: str) -> Optional[str]:
    """받침 없는 글자에 ㅂ 을 받쳐 준다. 하 → 합 · 다르 의 '르' → 릅"""
    o = ord(ch)
    if not (_BASE <= o <= _LAST) or (o - _BASE) % _JONG != 0:
        return None
    return chr(o + 17)          # ㅂ 은 종성 17번


# ══════════════════════════════════════════════════════════
# 한 낱말 바꾸기
# ══════════════════════════════════════════════════════════
#
# 다루는 꼴 — 문장 끝에 오는 하오체만
#     …시오   시키는 말 (하시오 · 마시오 · 주시오)
#     …소     받침 있는 어간 (있소 · 않소 · 읽소 · 않았소 · 보겠소)
#     …오     받침 없는 어간 (하오 · 보오 · 것이오 · 아니오 · 바뀌오)
# ★ 반말·하게체는 '시' 를 뗍니다.
#   「정하시지」는 반말이라면서 존대가 섞인 말입니다. 어간에 바로
#   붙입니다 — 하시오 → 하지(반말) · 하게(하게체).
_IMP_KEEP_SI = {HAPSYO: "십시오", HAEYO: "세요"}
_IMP_DROP_SI = {HAGE: "게", BANMAL: "지"}
_TAIL = {
    HAGE: "네",
    BANMAL: "지",
    HAEYO: "네요",
}

# ★ 묻는 문장은 어미가 다릅니다 (2026-09-03).
#
#   「그리 보이오?」 를 그냥 갈면 합쇼체가 「보입니다?」 가 됩니다.
#   서술문 어미에 물음표만 붙인 꼴이라, 읽는 사람은 그 자리에서
#   기계라는 걸 압니다. 묻는 꼬리는 이 집이 자주 씁니다 —
#   손님의 응답을 받는 자리가 전부 물음이기 때문입니다.
#
#   여기도 **어간은 안 건드립니다**. 어간에 붙이기만 하면 되는
#   꼴로만 짰습니다 — 않나 · 않나요 · 않습니까 · 보이나 · 보이나요.
_TAIL_Q = {
    HAGE: "나",
    BANMAL: "지",
    HAEYO: "나요",
}

# ══════════════════════════════════════════════════════════
# 명사 + 요 — 「자리요 · 나이요 · 庚戌요」
# ══════════════════════════════════════════════════════════
#
# ★ 이 꼴이 통째로 새고 있었습니다 (2026-09-03).
#
#   하오체는 받침 없는 명사 뒤에서 「…이오」 를 「…요」 로 줄입니다 —
#   「그것은 자리요」 「지금 33세요」 「일주는 庚戌요」. 어간이 없으니
#   위의 서술 규칙(오/소)에 안 걸려 **어떤 말투로도 안 바뀌었습니다.**
#   재보니 한 사람 리포트에 이 꼴이 서른~예순 자리였고, 그래서
#   합쇼체 캐릭터가 「…자리요. …그것입니다.」 처럼 한 문단 안에서
#   말투를 갈아탔습니다.
#
# ★ 받침 있는 명사는 이 꼴이 아닙니다.
#   하오체가 「…것이오」 로 쓰므로 이미 서술 규칙이 잡습니다. 여기서
#   받침을 보고 물러서지 않으면 「손요 → 손입니다」 같은 것이 나옵니다.
#
# ★ 해요체 어미는 건드리지 않습니다.
#   「흘러요 · 거든요 · 이지요」 도 「요」 로 끝납니다. 뱅크는 하오체
#   한 벌이라 원래 없어야 하지만, 하나라도 새면 「흘러입니다」 가
#   되므로 꼬리를 보고 물러섭니다.
# ★ 명사와 부딪히는 꼬리는 뺐습니다 — 「먼저요 · 동네요」 가 해요체
#   동사로 잘못 걸려 하오체로 남았습니다. 명사 쪽이 훨씬 잦습니다.
_YO_KEEP = ("네요", "세요", "예요", "에요", "아요", "어요", "여요", "워요",
            "와요", "해요", "돼요", "봐요", "줘요", "래요", "켜요", "쳐요",
            "펴요", "러요", "지요", "든요", "게요", "나요", "려요", "겨요",
            "죠")
_NOUN = {
    HAPSYO: "입니다",
    HAGE: "네",
    BANMAL: "지",
    HAEYO: "예요",
}


def _word(w: str, voice: str, ask: bool = False) -> str:
    """낱말 하나. 못 다루는 꼴이면 그대로 돌려준다."""
    if voice == HAO or not w:
        return w

    # ★ 태그 밖에 어미만 남은 자리 — 「<b>庚戌</b>요.」
    #   앞의 이름은 다른 조각에 있어 받침을 못 봅니다. 다만 받침이
    #   있으면 뱅크가 「…이오」 로 쓰므로, 홀로 남은 「요」 는 언제나
    #   받침 없는 이름 뒤입니다. 그래서 그냥 붙이면 됩니다.
    if w == "요":
        return _NOUN[voice]
    if len(w) < 2:
        return w

    # ── 시키는 말 ──────────────────────────────────────
    if w.endswith("시오"):
        if voice in _IMP_KEEP_SI:
            return w[:-2] + _IMP_KEEP_SI[voice]
        return w[:-2] + _IMP_DROP_SI[voice]

    # ── 명사 + 요 ──────────────────────────────────────
    if w.endswith("요"):
        # ★ 「33세요」 는 나이(명사)이고 「하세요」 는 시키는 말입니다.
        #   꼬리가 같아서 앞 글자로 가릅니다 — 숫자면 나이입니다.
        age = w.endswith("세요") and len(w) > 3 and w[-3].isdigit()
        if w.endswith(_YO_KEEP) and not age:
            return w
        noun = w[:-1]
        if not noun or _has_batchim(noun[-1]):
            return w
        return noun + _NOUN[voice]

    # ── 서술 ───────────────────────────────────────────
    end = w[-1]
    if end not in "오소":
        return w
    stem = w[:-1]
    if not stem:
        return w

    bat = _has_batchim(stem[-1])
    if bat is None:
        return w                      # 한글이 아니면 손대지 않는다

    # 받침 있는 어간에는 '소', 없는 어간에는 '오' 가 붙습니다.
    # 어긋나면 하오체가 아닌 다른 말이니 손대지 않습니다.
    if (end == "소") != bool(bat):
        return w

    # ㄹ 받침은 -ㅂ니다 · -네 앞에서 떨어집니다 (규칙)
    dropped = _drop_riul(stem[-1]) if bat else None

    if voice == HAPSYO:
        tail = "니까" if ask else "니다"
        if dropped:
            made = _add_bieup(dropped)
            return (stem[:-1] + made + tail) if made else w
        if bat:
            return stem + ("습니까" if ask else "습니다")
        made = _add_bieup(stem[-1])
        return (stem[:-1] + made + tail) if made else w

    if voice == HAGE and dropped:
        return stem[:-1] + dropped + ("나" if ask else "네")

    # 해요체·반말 — 서술문에서는 아/어를 답니다. 물음은 위의 표로.
    if voice in (HAEYO, BANMAL) and not ask:
        # ★ 「…것이오 · 일이오 · 끝이오」 의 이는 **이다**입니다.
        #   해요체는 「것이에요」, 반말은 「것이야」 입니다. 「것이네요」 로
        #   두면 이 꼴이 가장 잦아서 「네요」 가 절반을 넘어갑니다.
        #
        #   「보이오 · 쓰이오」 의 이는 어간의 일부라 「보여요」 로 줄어듭니다
        #   — 그건 못 만듭니다. 가르는 자리는 **바로 앞 글자의 받침**입니다.
        #   이다는 받침 있는 이름 뒤에 곧바로 붙고(것이·일이), 어간의 이는
        #   받침 없는 글자 뒤에 옵니다(보이·쓰이).
        if len(stem) >= 2 and stem[-1] == "이" and _has_batchim(stem[-2]):
            return stem[:-1] + ("이에요" if voice == HAEYO else "이야")
        cut = _CONTRACT.get(stem[-1])
        if cut:
            return stem[:-1] + cut[0 if voice == HAEYO else 1]
        add = _a_eo(stem)
        if add:
            return stem + add + ("요" if voice == HAEYO else "")

    return stem + (_TAIL_Q if ask else _TAIL)[voice]


# ══════════════════════════════════════════════════════════
# 글 한 덩이 바꾸기
# ══════════════════════════════════════════════════════════
#
# ★ HTML 안쪽만 건드립니다. 태그(<b>, <p class="..">)는 그대로 둡니다 —
#   속성값에 손대면 화면이 깨집니다.
_TAGS = re.compile(r"<[^>]*>")

# 문장 끝 — 문장부호 앞이나, 글/태그가 끝나는 자리
#
# ★ 줄표(—) 앞을 놓치고 있었습니다.
#   "여덟 자리를 넷으로 추렸소 — 빈 기운 · 힘 · 곁을 돕는 자리" 에서
#   `추렸소` 가 안 바뀌어, 하게체 캐릭터가 갑자기 하오체로 말했습니다.
#   재보니 스무 명에서 **마흔네 번** 그랬습니다. 줄표는 이 집이 자주
#   쓰는 문장부호라 그만큼 많이 샜습니다.
#
# ★ 출처 묶음표(〔…〕) 앞도 놓치고 있었습니다 (2026-09-03).
#   근거 줄은 「…그걸 어디서 얻는지를 보오 〔자평 명리 · 용신〕」 처럼
#   **어미 뒤에 출처가 붙어** 끝납니다. 그래서 `보오` 가 문장 끝으로
#   안 잡혀, 해요체 약초의원의 리포트에서 근거 줄만 하오체로 남았습니다.
#   손님이 그걸 보고 멈췄습니다 — 한 화면에 말투가 둘이었습니다.
#   `engine/why.py` 가 이 꼴을 쓰므로 근거 줄 **전부**가 새고 있었습니다.
#
# ★ 한글만 잡으면 「庚戌요 · 33세요 · 내놓는 힘)요」 를 놓칩니다.
#   앞 글자가 한자·숫자·괄호면 한글 덩이가 「요」 한 자뿐이라 {2,} 에
#   안 걸렸습니다. 공백이 아닌 덩이로 잡고, 손댈지 말지는 _word 가
#   가립니다 — 한글이 아니면 거기서 그대로 돌려보냅니다.
#
# ★ 한 글자도 잡습니다 — 「<b>庚戌</b>요.」 처럼 **이름은 태그 안**에 있고
#   어미만 밖에 남는 자리가 흔합니다. 두 글자를 요구하면 그 자리가
#   통째로 안 바뀌어, 합쇼체 캐릭터가 「…<b>庚戌</b>요.」 라고 말했습니다.
_ENDING = re.compile(r"([^\s.!?…—–〔]+)(?=\s*(?:([.!?…])|[—–]|〔|$))")


def _piece(text: str, voice: str) -> str:
    return _ENDING.sub(
        lambda m: _word(m.group(1), voice, ask=(m.group(2) == "?")), text)


