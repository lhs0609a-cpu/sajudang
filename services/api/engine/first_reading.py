def build_first_reading(f, concern: str, axis4=None, name: str = '',
                        you: str = '그대', misses: int = 0, topic=None) -> list:
    """
    다섯 마디. 판정 → 까닭·반증 → 오늘 하나·확인법 → 대 보기 → 다음 물음.

    ★ `topic` 은 손님이 앞서 고른 객관식이오. v2 는 이걸 **안 받았습니다.**
      다섯을 물어 놓고 한 개도 안 봤으니, 손님이 「제대로 물어보는 것도
      아니다」 한 것이 맞는 말이었소.
    """
    from .bank import axis_compare, BankError
    from .mbti_reading import build as build_mbti
    if concern not in RANK:
        raise BankError('모르는 고민 축: %s' % concern)

    sub = topic if isinstance(topic, dict) and topic else None
    got = _candidates(f, concern, sub)
    # ★ 두 번 「아니오」면 **둘째 후보**로 갑니다. 포기 문구로 바꾸던
    #   자리였소 — 손님이 지운 것은 후보를 줄인 것이지 물음을 접은
    #   것이 아니오.
    key = got[1] if (misses >= 2 and len(got) > 1) else got[0]
    cell = CELL[(concern, key)]
    c1 = _count(f, concern, FACTS[key][0], sub)
    c2 = _count(f, concern, FACTS[key][1], sub)
    bag = {'c1': escape(c1), 'c2': escape(c2)}
    picks = _picked(concern, sub)

    head = ''
    if name.strip():
        head += ('<p class="first-reading-name">%s, 이 자리부터 가르겠소.</p>'
                 % escape(name.strip()))
    if misses >= 2:
        head += ('<p class="fr-turn">앞서 두 대목이 아니라 하셨소. '
                 '같은 자리를 <b>다른 글자로</b> 다시 가르오.</p>')
    if len(picks) > 1 and picks[0] and picks[1]:
        head += ('<p class="fr-said">고르신 두 자리를 <b>맞물려</b> 보겠소 — '
                 '%s · %s.</p>' % (escape(picks[0]), escape(picks[1])))
    elif picks and picks[0]:
        head += ('<p class="fr-said">고르신 자리는 <b>%s</b>%s소.</p>'
                 % (escape(picks[0]), _was(picks[0])))

    # ★ 찌르고 **그 아래에** 무엇을 보고 한 말인지 적습니다.
    #   센 값을 위에 두면 첫 문장이 판정이 아니라 강의가 되오.
    counts = '<p class="fr-count"><b>%s</b>%s</p>' % (
        bag['c1'], (' · <b>%s</b>' % bag['c2']) if c2 else '')
    s0 = (head
          + '<p class="first-reading-scene">%s %s</p>' % (cell['no'], cell['yes'])
          + counts)
    # ★ 마디마다 접히는 화면이오. 1단만 펴 본 손님에게도 수가 보여야
    #   하니 센 값을 다시 답니다 — 다만 **줄을 나눕니다.** 까닭 문장
    #   앞에 붙이면 「겉에 1자 — 쓰는 글자가…」 처럼 줄표가 둘이 되오.
    s1 = (counts
          + '<p class="first-reading-emphasis">%s</p>' % _fill(cell['why'], bag)
          + '<p class="fr-wrong">이 읽기가 <b>틀리는 자리</b>는 여기요 — %s</p>'
          % WRONG[key]
          + '<p class="fr-guard">%s</p>' % GUARD_LINE[concern])
    # ★ 표지판은 말이 아니오 — 어미를 달지 않소. 「…이것으로 아오」 를
    #   두었더니 해요체 캐릭터에게서 「이것으로 아네요」 라는 비문이 났소.
    s2 = ('<p class="first-reading-action">%s</p>' % cell['act']
          + '<p class="fr-check"><b>맞았는지 재는 법</b> — %s</p>'
          % cell['check'])

    # ── 넷째 마디 — 댈 것이 있으면 넉 자, 없으면 **때** ──────
    cmp4 = axis_compare(f, axis4)
    mbti = build_mbti(f, axis4, concern)
    if cmp4['usable']:
        label4 = LABELS['2.5']
        line = (cmp4['gaps'][0]['t'] if cmp4['gaps']
                else cmp4['matches'][0]['t'])
        s25 = ('<p>고르신 <b>%s</b> 넉 자와 그대 글자로 읽은 넉 자를 대니 '
               '<b>%d곳</b>이 닮고 <b>%d곳</b>이 갈렸소.</p>'
               % (escape((axis4 or '').upper()),
                  len(cmp4['matches']), len(cmp4['gaps']))
               + '<p class="first-reading-emphasis">%s</p>' % line
               + '<p class="fr-wrong">달라도 그대가 그대를 잘못 아는 것이 '
                 '아니오 — 자리마다 달라지는 모습이 있는지 보시오.</p>')
        if mbti:
            s25 += '<p class="fr-check">%s</p>' % escape(mbti['question'])
        src4 = ('고르신 넉 자와 이 집이 여덟 글자로 읽은 넉 자를 댄 것이오. '
                '성격을 판정하는 검사가 아니고, 생년월일 셈도 안 바뀌오.')
        if not f.hour_known:
            src4 = src4.replace('여덟 글자로', '세 기둥으로')
    else:
        label4 = LABELS['2.5t']
        dc = _count(f, concern, 'daeun_group', sub)
        nxt, now = _turn_age(f), int(f.age)
        s25 = '<p class="fr-count"><b>%s</b></p>' % escape(dc)
        if nxt > now:
            s25 += ('<p>지금 <b>%d살</b>이오. 이 구간은 <b>%d살</b>에 갈리오 '
                    '— %s 남았소.</p>' % (now, nxt, _years(nxt - now)))
        else:
            s25 += ('<p>지금 <b>%d살</b>이오. 다음 구간은 표에 없어 안 세오.</p>'
                    % now)
        s25 += ('<p class="first-reading-emphasis">그 해에 무슨 일이 생긴다는 '
                '말이 아니오. <b>보는 자리가 바뀐다</b>는 말이오. 지금의 '
                '가름은 그때까지의 가름이오.</p>')
        src4 = _why.axis_line(escape('%s · 지금 %d살' % (dc, now)), 'daeun_phase')

    s3 = ''
    if len(picks) > 2 and picks[2]:
        s3 += ('<p class="fr-said">알고 싶다 하신 것은 <b>%s</b>%s소.</p>'
               % (escape(picks[2]), _was(picks[2])))
    s3 += '<p class="first-reading-scene">%s</p>' % cell['next']
    s3 += ('<p>오늘 할 일은 이미 그대 손에 있소. 그 까닭이 궁금하거든 '
           '<b>다음 무료 풀이</b>에서 이어 보시오.</p>')

    src = _source(f, concern, key, c1, c2)
    specs = [('0', LABELS['0'], s0, src),
             ('1', LABELS['1'], s1, src),
             ('2', LABELS['2'], s2, src),
             ('2.5', label4, s25, src4),
             ('3', LABELS['3'], s3, src)]

    # ★ 어려운 말은 **한 벌 안에서 한 번**만 풉니다. 다섯 마디가
    #   한 벌이오 (`terms.gloss` 의 seen).
    seen = set()
    out = []
    for stage, label, body, evidence in specs:
        if misses >= 2 and stage in ('0', '2'):
            evidence = ('앞선 두 마디에서 맞지 않는다고 알려 주어 둘째 '
                        '후보로 가름을 바꾸었소. 사주 셈은 안 바뀌었소.')
        body = terms.gloss(body, seen, concern, f.sex)
        evidence = terms.gloss(evidence, seen, concern, f.sex)
        addressed = voice.address(body, escape(you))
        yes_reply, no_reply = (voice.address(t, you) for t in REPLIES[stage])
        sid = '%s:%s:%s:%s:%s' % (
            VERSION, concern, key, stage,
            sha256((addressed + evidence + yes_reply + no_reply)
                   .encode()).hexdigest()[:16])
        out.append(dict(
            stage=stage, label=label,
            html=guard.enforce(addressed, {'statement_id': sid}),
            source=guard.enforce(evidence, {'statement_id': sid}),
            source_below=True, statement_id=sid,
            question=ASKS[stage], yes=yes_reply, no=no_reply))
    return out
