def _count(f, concern: str, fact_id: str, sub) -> str:
    """센 값 한 줄. 표가 그 고민을 모르면 돈 축으로 물러섭니다."""
    for c in (concern, 'money'):
        try:
            got = _topic.count_of(f, c, fact_id, sub)
        except Exception:
            got = None
        if got:
            return got[1]
    return ''


def _focus_keys(concern: str, sub) -> list:
    out = []
    if not sub:
        return out
    # ★ **새는 자리가 먼저**요. 「어디서 오오」 보다 「어디서 걸리오」
    #   가 물음에 가깝소. 둘을 뒤집어 두었더니 들어오는 자리가 늘 이겨
    #   서, 새는 자리를 무엇으로 고르든 같은 판정이 나갔습니다
    #   (마흔 사람 중 한 사람만 갈림).
    for slot, field in (('leak', 'choice2'), ('from', 'choice')):
        out += FOCUS.get((concern, slot, str(sub.get(field) or '')), [])
    return out


def _candidates(f, concern: str, sub) -> list:
    """이 사람에게 **실제로 걸린** 판정들. 차례는 드문 것이 앞이오."""
    order = RANK.get(concern) or []
    got = []
    if order:
        hit = {p['key'] for p in _pattern.read(f, concern, limit=99)}
        pri = _focus_keys(concern, sub)
        got = sorted([k for k in order if k in hit and (concern, k) in CELL],
                     key=lambda k: (0 if k in pri else 1,
                                    pri.index(k) if k in pri else order.index(k)))
    base = 'base_weak' if f.strength != '신강' else 'base_strong'
    for k in (base, 'base_strong' if base == 'base_weak' else 'base_weak'):
        if (concern, k) in CELL and k not in got:
            got.append(k)
    return got


def _turn_age(f) -> int:
    """다음 대운이 드는 나이. 표에 없으면 0 — **지어내지 않소.**"""
    rows = list(f.daeun or [])
    i = int(f.daeun_now) + 1
    if 0 <= i < len(rows):
        try:
            return int(rows[i].get('start_age') or 0)
        except (TypeError, ValueError):
            return 0
    return 0


def _picked(concern: str, sub) -> list:
    """손님이 고른 것의 **사람 말**. 목록에 없는 값은 안 싣소."""
    if not sub:
        return []
    try:
        spec = (_topic.table()['ASK'].get(concern)
                or _topic.table()['ASK'].get('money') or {})
    except Exception:
        return []
    out = []
    for field, bag in (('choice', 'options'), ('choice2', 'options2'),
                       ('choice3', 'options3')):
        val = str(sub.get(field) or '')
        opts = spec.get(bag) or {}
        out.append(opts.get(val, ''))
    return out


def _fill(text: str, bag: dict) -> str:
    return text.format(**bag) if '{' in text else text


def _was(word: str) -> str:
    """「…였소 / …이었소」 — 받침을 보고 답니다.

    ★ 「번 돈을 지키는 방법였소」 가 나가던 자리요. 자리표시 뒤에
      조사를 손으로 박으면 반드시 이 사고가 납니다 (CLAUDE.md).
    """
    from .bank import has_batchim
    return '이었' if word and has_batchim(word) else '였'


_YEAR_WORD = ('', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉', '열')


def _years(n: int) -> str:
    """「3해」 도 「셋 해」 도 아니오 — 「세 해」. 매김씨 꼴이라야 하오."""
    n = int(n)
    return '%s 해' % (_YEAR_WORD[n] if 0 < n < len(_YEAR_WORD) else str(n))


def _pillars_word(f) -> str:
    return '네 기둥' if f.hour_known else '세 기둥 · 태어난 시각 제외'


def _source(f, concern: str, key: str, c1: str, c2: str) -> str:
    seen = '%s · %s일간 · %s' % (_pillars_word(f), f.day_gan,
                                ' · '.join(x for x in (c1, c2) if x))
    return _why.axis_line(escape(seen), AXIS_OF.get(key, 'top_ten_god'))


