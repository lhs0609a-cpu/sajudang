def phase_of(age: int, start: int) -> str:
    """이 대운 칸의 어디쯤인가. 한 칸은 십 년이오."""
    if age < start:
        return "before"
    into = (age - start) % 10
    if into < 3:
        return "early"
    if into < 7:
        return "mid"
    return "late"


