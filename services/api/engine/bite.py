# 십신 열을 다섯으로 접는 자리
GROUP_OF = {
    "비견": "비겁", "겁재": "비겁",
    "식신": "식상", "상관": "식상",
    "편재": "재성", "정재": "재성",
    "편관": "관성", "정관": "관성",
    "편인": "인성", "정인": "인성",
}


def group_of(ten_god: str) -> str:
    """십신 이름을 다섯 묶음 중 하나로."""
    return GROUP_OF.get(ten_god, ten_god)


def line(concern: str, ten_god: str, strength: str = "") -> str:
    """
    뼈 때리는 한 줄. 모르는 짝이면 빈 문자열.

    ★ 지어내지 않습니다. 표에 없으면 안 붙입니다 — 아무 말이나
      세게 하면 그건 팩폭이 아니라 헛소리입니다.
    """
    got = BITE.get(concern, {}).get(group_of(ten_god), "")
    if not got:
        return ""
    edge = EDGE.get(strength, "")
    return got + (" " + edge if edge else "")


def wrap(txt: str, key: str, seen: Optional[set] = None) -> str:
    """
    화면에 넣을 꼴. 같은 줄은 한 장에 **두 번 안 나갑니다.**

    ★ 「엄청 많이」 는 자주 때리라는 말이지, **같은 자리를** 스무 번
      때리라는 말이 아닙니다. 같은 말이 두 번째로 돌아오는 순간
      손님은 이게 녹음이라는 걸 압니다 — 훅에서 이미 겪은 일입니다.

      그래서 축을 셋으로 두었습니다 (고민 × 묶음 · 없는 기운 ·
      대운 국면). 서로 무관한 축이라 한 장에서 서로 다른 데를
      때립니다.
    """
    if not txt:
        return ""
    if seen is not None:
        if key in seen:
            return ""
        seen.add(key)
    return '<p class="bite">%s</p>' % txt


def html(concern: str, ten_god: str, strength: str = "",
         seen: Optional[set] = None) -> str:
    """고민 축 — 물으러 온 그 자리를 때린다."""
    return wrap(line(concern, ten_god, strength),
                "c:%s:%s" % (concern, group_of(ten_god)), seen)


def lack_html(weak_el: str, seen: Optional[set] = None) -> str:
    """없는 기운 축 — 고민이 무엇이든 그 사람에게 그대로 있는 것."""
    return wrap(LACK.get(weak_el, ""), "l:%s" % weak_el, seen)


def phase_html(age: int, start: int, seen: Optional[set] = None) -> str:
    """대운 국면 축 — 지금 판의 어디쯤인가."""
    p = phase_of(age, start)
    return wrap(PHASE.get(p, ""), "p:%s" % p, seen)
