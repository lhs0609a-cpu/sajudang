# -*- coding: utf-8 -*-
"""
쉬어 가는 자리 — 아프게 한 뒤의 책임

★ 손님이 시킨 것 (2026-09-16)

  "이거의 핵심은 정말 팩폭하면서도 동시에 위로를 줘야 한다는 거야.
   희망이 생겨야 해 삶에. 그로 인해서 자살하는 사람이 늘어나지
   않도록 설계해줘."

★ 이 집은 아프게 하는 집입니다

  팩폭 축이 그걸 점수로 매기고, 뱅크는 「틀릴 수 없는 말만 쓰기」를
  금합니다. 그건 맞습니다 — 아프지 않은 말은 아무것도 안 바꿉니다.

  그런데 아프게 하는 집에는 **아프게 한 뒤의 책임**이 따릅니다.
  2026-09-16 에 재 보니 이 저장소 어디에도 도움 받을 곳이 한 줄도
  없었습니다. 엔진에도 화면에도 문서에도요.

★ 무엇을 보고 여는가 — **행동**입니다

  이 집은 자유 입력을 안 받습니다 (맥락축에 자유 입력 금지 —
  개인정보가 섞이고 가드를 우회합니다). 그러니 「죽고 싶다」 같은
  말을 적을 자리가 없고, 글로는 알 수 없습니다.

  대신 **셀 수 있는 것**만 봅니다. 셋이 겹치면 엽니다.

      되풀이       하루에 세 번 넘게 옴 (retention 의 만류와 같은 값)
      안 맞음      훅 다섯 마디에 「아니오」가 넷 이상 —
                   이 집의 말이 안 맞는 사람이오. 더 읽어도 안 맞소
      늦은 때      밤 0~5시에 왔고, 오늘 처음이 아님
      몸           물으신 자리가 몸(health)이고 되풀이 온 사람

  ★ 이건 **진단이 아닙니다.** 누가 위험한지 우리는 모릅니다.
    아는 것은 「이 사람이 오늘 이 집을 오래 붙들고 있다」 뿐이오.
    그래서 여는 것도 진단이 아니라 **문 하나**입니다.

★ 열면 무엇을 하는가 — 세 가지를 **안 합니다**

    조르지 않소     값을 권하지 않습니다. 여기서는 아무것도 안 팝니다
    진단하지 않소   「우울하시군요」 는 이 집이 할 말이 아니오.
                   병명은 가드가 막고 있고, 막는 게 맞습니다
    붙잡지 않소     「더 보시오」 가 아니라 「오늘은 여기까지」 요

  하는 것은 하나입니다 — **오늘 여기서 그만두어도 된다고 말하고,
  도움 받을 곳을 적어 둡니다.**

★ 번호는 적어 두기만 합니다

  이 집이 상담하지 않습니다. 상담은 상담하는 데가 합니다.

      자살예방 상담전화       109
      정신건강위기 상담전화    1577-0199
      청소년 전화            1388

  ★ 바꾸지 마시오. 번호가 틀리면 그건 없는 것만 못합니다.
"""
from __future__ import annotations

from typing import Optional

# 도움 받을 곳. 화면과 엔진이 **같은 표**를 씁니다 —
# 두 벌을 들면 한쪽만 고쳐져 틀린 번호가 나갑니다.
LINES = (
    {"name": "자살예방 상담전화", "tel": "109", "when": "24시간"},
    {"name": "정신건강위기 상담전화", "tel": "1577-0199", "when": "24시간"},
    {"name": "청소년 전화", "tel": "1388", "when": "24시간"},
)

# 몇이 겹쳐야 여는가. 하나로는 안 엽니다 — 밤에 한 번 온 것은
# 그냥 밤에 한 번 온 것이오.
OPEN_AT = 2

# 하루에 몇 번부터 「되풀이」 로 보는가. `retention` 의 만류와 같은 값.
VISITS_AT = 3
# 훅 다섯 마디에 「아니오」가 몇이면 안 맞는 것으로 보는가.
MISS_AT = 4


def signals(visits: int = 0, hook_misses: int = 0, hour: Optional[int] = None,
            concern: Optional[str] = None, returning: bool = False) -> list:
    """겹친 신호. **세는 값**만 봅니다 — 지어내지 않습니다.

    visits        오늘 몇 번째 왔는가
    hook_misses   훅에서 「아니오」가 몇이었는가
    hour          지금 몇 시인가 (0~23 · 서울)
    concern       물으신 자리
    returning     오늘 처음이 아닌가
    """
    out = []
    if visits >= VISITS_AT:
        out.append("되풀이")
    if hook_misses >= MISS_AT:
        out.append("안 맞음")
    if hour is not None and 0 <= hour <= 5 and returning:
        out.append("늦은 때")
    if concern == "health" and returning:
        out.append("몸")
    return out


def should_open(**kw) -> bool:
    return len(signals(**kw)) >= OPEN_AT


def rest(you: str = "그대", signals_: Optional[list] = None) -> dict:
    """쉬어 가는 자리 한 벌.

    ★ 말투는 집의 것(하오체) 한 벌로 씁니다. `voice.speak` 가
      캐릭터마다 어미를 갈 수 있게요. 다만 이 자리만은 **캐릭터를
      안 태우는 쪽**을 권합니다 — 여기서 말하는 것은 캐릭터가 아니라
      집입니다.

    ★ 여기에 셈을 대지 않습니다. 이 자리는 근거 대는 자리가 아니라
      **그만두어도 된다고 말하는 자리**요.
    """
    why = signals_ or []
    head = "오늘은 여기까지 두시오."
    if "되풀이" in why:
        body = ("오늘 이 집에 여러 번 오셨소. 같은 글자를 여러 번 읽는다고 "
                "답이 더 나오지는 않소 — 여덟 글자는 오늘도 어제와 같소.")
    elif "안 맞음" in why:
        body = ("여러 마디를 두고 아니라 하셨소. 그건 %s가 틀린 게 아니라 "
                "이 집의 말이 %s에게 안 맞는 것이오. 안 맞는 말을 더 읽을 "
                "까닭이 없소." % (you, you))
    elif "늦은 때" in why:
        body = ("늦은 시각이오. 밤에 읽은 말은 아침에 읽은 것보다 무겁게 "
                "남소 — 같은 글인데도 그렇소. 내일 다시 펴도 글자는 "
                "그대로 있소.")
    else:
        body = ("오늘은 여기서 덮어 두셔도 되오. 여덟 글자는 도망가지 "
                "않소.")
    return {
        "id": "rest",
        "title": "쉬어 가는 자리",
        "head": head,
        "body": body,
        # 이 집이 못 하는 일이 있다는 것을 적습니다. 이건 겸양이 아니라
        # 사실이오 — 명식은 사람을 못 살립니다.
        "limit": ("이 집은 여덟 글자를 셀 뿐이오. 마음이 많이 힘들 때는 "
                  "사람에게 말하시오 — 셈으로는 안 되는 자리가 있소."),
        "lines": [dict(x) for x in LINES],
        "why": list(why),
    }
