# 강조 — 어디부터 보라고 정해 주는가
# ══════════════════════════════════════════════════════════
#
# ★ 손님이 짚은 것 (2026-09-04)
#
#   "화면에 글이 너무 많은데 전부 어떻게 설계할 거야?"
#
#   그 말을 하며 보고 있던 화면은 a1 골목이었습니다. 그런데 a1 은
#   스물아홉 화면 중 **가장 짧습니다** — 253자 · 28초. 읽기속도는
#   만점이었습니다. 양이 문제가 아니었습니다.
#
#   세어 보니 253자에 굵은 글씨가 **일곱 군데**였습니다. 200자당
#   5.5군데로 스물아홉 중 최고이고, 중앙값(2.2)의 두 배 반입니다.
#   덩이 다섯이 전부 가운데 정렬에 전부 같은 크기인데 강조만 일곱이면,
#   눈이 어디부터 볼지 못 정합니다. **다 굵으면 아무것도 안 굵습니다.**
#   그래서 253자가 많게 느껴집니다.
#
# ★ 없어도 마찬가지입니다
#
#   c2 본문은 10,244자에 굵은 글씨가 **둘**입니다(200자당 0.04).
#   만 자를 쏟아 놓고 어디가 중한지 한 번도 안 짚은 것입니다. 너무
#   많은 것과 아예 없는 것은 같은 병입니다 — 위계가 없습니다.
#
# ★ 구간은 실제 분포에서 잡았습니다 (지어내지 않았습니다)
#
#   스물아홉 화면: 최소 0.0 · 25% 1.2 · 중앙 2.2 · 75% 3.1 · 최대 5.5
#   낮은 쪽은 본문·마감처럼 글이 긴 자리이고, 높은 쪽은 A 구간
#   입력 화면입니다. 중앙 언저리를 좋은 구간으로 둡니다.
# ★ 엔진이 박는 굵은 글씨는 **안 셉니다** (2026-09-04)
#
#   처음에는 화면에 나온 <b> 를 다 셌습니다. 그랬더니 c3 대운 맵이
#   0점이 됐습니다 — 엔진이 대운 칸마다 나이를 굵게 박기 때문입니다.
#   c2 본문은 192군데였습니다.
#
#   그건 장식이 아니라 **근거 값**입니다. 이 집은 나이·연도·센 수를
#   박으라고 못박아 두었습니다(CLAUDE.md). 게다가 c2 는 컷이 한 개씩
#   뜨는 자리라, 192군데가 한 번에 서 있지도 않습니다.
#
#   손님이 짚은 것은 **화면이 제 손으로 쓴 글**이었습니다 — a1 은
#   253자에 일곱 군데를 손으로 박아 두었습니다. 그래서 화면 제 글에서만
#   셉니다. 엔진 글의 강조는 다른 자가 봅니다(근거·희소도).
#
# ★ 구간은 실제 분포에서 잡았습니다 (지어내지 않았습니다)
#
#   화면 제 글 기준 스물아홉 화면:
#     최소 0.7 · 25% 1.9 · 중앙 2.5 · 75% 3.1 · 90% 4.0 · 최대 5.5
#   중앙값을 좋은 구간의 위끝으로 둡니다. 아래끝은 낮게 둡니다 —
#   지금은 아무도 안 걸립니다. 앞으로 한 군데도 안 짚는 화면이
#   생기면 그때 잡으라고 세워 둔 자리입니다.
MARK_PER = 200.0      # 이만큼 글자마다 세어 봅니다
MARK_LOW = 0.5        # 이보다 적으면 짚어 주는 데가 없소
MARK_OK = 2.5         # 여기까지가 좋소 (중앙값)
MARK_HIGH = 5.0       # 여기부터는 다 굵은 것과 같소


def score(sid: str, title: str, html: str, kind: str = "read",
          next_named: Optional[str] = None,
          declared: Optional[list] = None,
          addressed: bool = False,
          folded: int = 0,
          marks: int = 0,
          own: int = 0) -> dict:
    """
    화면 하나의 네 점수와 **무엇이 모자란지**.

    sid        화면 이름 (a1 · c2 …)
    html       손님이 실제로 읽는 글 (HTML 그대로)
    kind       input 입력 · beat 한 마디 · read 읽는 자리 · list 고르는 자리
    next_named 화면 밖에서 다음 자리를 이름으로 예고했으면 그 이름
    declared   화면이 `<ActOut kind="딜레마">` 로 **선언한** 액트아웃
    addressed  화면이 손님을 **그 사람의 호칭**으로 부르는가
               (`{you}` — 캐릭터마다 그대·자네·손님·아저씨로 갈립니다)

    ★ 왜 선언을 받나

      말뭉치로만 찾으면 글을 고칠 때마다 정규식을 쫓아가게 됩니다.
      그건 글을 고치는 게 아니라 **검사에 맞춰 쓰는 것**입니다.

      `ActOut` 은 자리가 고정된 부품이고(버튼 바로 위) 무슨 꼴인지
      스스로 적습니다. 그러면 그건 **있는 것**입니다. 말뭉치는
      부품을 안 쓰는 자리 — 엔진이 짓는 글 — 를 위해 남겨 둡니다.
    """
    body = GLS.sub(" ", html or "")
    text = plain(body)
    lines = _lines(text)
    n = len(text)
    miss = []

    # ── ① 당김 ────────────────────────────────────────────
    # ★ 끝을 **마지막 두 문장**으로만 보면 안 됩니다.
    #
    #   화면 글은 파일에 적힌 순서대로 읽히는데, 막을 끊는 줄 뒤에도
    #   버튼 · 고지 · 각주가 따라붙습니다. 두 문장만 보면 액트아웃을
    #   써 넣고도 「없다」 고 나옵니다 — 실제로 그렇게 나왔습니다.
    #
    #   그래서 **뒤 40%** 안에 있으면 셉니다. 미드에서도 액트아웃은
    #   막의 마지막 한 줄이 아니라 마지막 **비트**입니다.
    cut = max(1, int(len(lines) * 0.6))
    tail = " ".join(lines[cut:]) if lines else ""
    last = lines[-1] if lines else ""

    cold = 25 if _cold_open(lines) else 0
    if not cold:
        miss.append("콜드 오픈이 없소 — 첫 줄이 설명이오. 사건이나 물음부터 여시오")

    kinds = list(declared or [])
    kinds += [k for k, rx in ACT_OUT.items()
              if rx.search(tail) and k not in kinds]
    act = 30 if kinds else 0
    if not act:
        miss.append("액트아웃이 없소 — 끝이 그냥 끝나오. "
                    "밝힘·뒤집기·딜레마·끊긴 동작·남긴 물음 중 하나로 끊으시오")

    named = 25 if (NAMED_NEXT.search(body) or next_named) else 0
    if not named:
        miss.append("다음을 이름으로 안 부르오 — 「더 있소」는 예고가 아니오")

    button = 20 if (last and len(last) <= 42) else 0
    if not button:
        miss.append("버튼이 무디오 — 마지막 한 줄을 짧게 끊으시오 (42자 이내)")

    pull = cold + act + named + button

    # ── ② 팩폭 ────────────────────────────────────────────
    f_hits = len(FALSIFIABLE.findall(text))
    air = len(AIR.findall(text))
    life = len(LIFE.findall(text))
    hedge = len(HEDGE.findall(text))

    s_fals = round(40 * _pct(f_hits, max(3, n / 260)))
    if s_fals < 24:
        miss.append("틀릴 수 없는 말이오 — 수·글자·해 본 행동을 박으시오")
    s_life = round(35 * _pct(life, max(1, air)))
    if s_life < 21:
        miss.append("뜬 말이 산 말보다 많소 — 돈·잠·연락 같은 살림의 말로 바꾸시오")
    s_firm = round(25 * (1 - _pct(hedge, max(2, n / 220))))
    if s_firm < 15:
        miss.append("물러서는 말이 많소 — 「게요·아마·쯤」을 걷으시오")
    bite = s_fals + s_life + s_firm

    # ── ③ 울림 — 눈물이 핑 도는가 ──────────────────────────
    #
    # ★ 손님이 시킨 것 중 여태 **하나도 안 세던** 축입니다.
    #
    #   "미드처럼 다음 무조건 보게 만들고, 팩폭하고, **감성적으로 눈물이
    #   핑 돌게** 하고, 명확하고, 쉽게 설명하고, **비유로** 설명하고,
    #   이런 거 점수로 만들어서 각 페이지마다 몇 점인지 띄워."
    #
    #   넷만 세고 있었습니다 — 당김·팩폭·충실·쉬움. 울림과 비유는
    #   자리가 없었고(비유는 쉬움 안에 25점으로 얹혀 있었습니다),
    #   그래서 「눈물이 핑」 은 아무도 안 재고 있었습니다.
    #
    # ★ 감정은 **못 세는 것**이 아닙니다. 세는 자리를 정하면 됩니다.
    #
    #   울림은 「슬픈 낱말」이 아니라 **누구 얘기인가 · 겪은 일인가 ·
    #   짧게 끊는가** 에서 옵니다. 넷을 셉니다.
    #
    # ★ 그리고 훈계는 **감점**입니다.
    #
    #   「힘내시오」 「마음먹기 나름이오」 는 감정을 건드리는 게 아니라
    #   가르치는 것입니다. 손님이 울컥하는 건 알아준다고 느낄 때지
    #   훈계받을 때가 아닙니다. 이 집이 금지한 단정(docs/11)과 같은 결.
    # ★ 호명은 말뭉치로만 찾으면 **잘 쓴 화면을 깎습니다.**
    #
    #   화면에 「그대」 라고 박아 두면 자는 셉니다. 그런데 그 화면은
    #   자네라 부르는 사람에게도 「그대」 라고 말합니다 — 스무 명 중
    #   열일곱이 틀린 말을 하게 됩니다. 제대로 고친 화면(`{you}`)은
    #   값이라 글에 안 남고, 그래서 0점이 됐습니다.
    #
    #   선언은 읽습니다. `kind` · `next` 와 같은 자리입니다.
    named_you = 25 if (addressed or YOU.search(text)) else 0
    if not named_you:
        miss.append("누구한테 하는 말인지 없소 — 「그대」 로 부르시오")
    feel_hits = len(FEEL.findall(text))
    s_feel = round(30 * _pct(feel_hits, max(1, n / 320)))
    if s_feel < 18:
        miss.append("겪은 마음의 말이 없소 — 참다·미루다·지치다 같은 말이오")
    s_lived = 25 if LIVED.search(text) else 0
    if not s_lived:
        miss.append("겪은 일을 안 짚소 — 「~했을 게요」 처럼 지난 일을 대시오")
    s_short = 20 if any(len(x) <= 14 for x in lines) else 0
    if not s_short:
        miss.append("숨 끊는 짧은 줄이 없소 — 열네 자 아래 한 줄을 두시오")
    preach = len(PREACH.findall(text))
    heart = max(0, named_you + s_feel + s_lived + s_short - 20 * min(1, preach))
    if preach:
        miss.append("훈계가 섞였소 — 「힘내시오」 는 알아주는 말이 아니오")

    # ── ④ 명확 — 무엇을 보고 한 말인지 분명한가 ────────────
    floor = FLOOR.get(kind, FLOOR["read"])
    s_len = round(20 * _pct(n, floor))
    if s_len < 12:
        miss.append("분량이 얇소 — %d자 자리에 %d자요" % (floor, n))
    has_src = 30 if re.search(r'class="src"|근거 ·|근거·', html or "") else 0
    if not has_src and kind in ("read", "beat"):
        miss.append("근거 줄이 없소 — 무엇을 보고 한 말인지 적으시오")
    counted = len(re.findall(r"\d", text))
    s_cnt = round(25 * _pct(counted, 6))
    if s_cnt < 15:
        miss.append("셀 수 있는 값이 적소 — 개수·나이·해를 내시오")
    avg = (sum(len(x) for x in lines) / len(lines)) if lines else 0
    s_sent = 25 if avg and avg <= 46 else (12 if avg and avg <= 60 else 0)
    if s_sent < 25:
        miss.append("문장이 기오 — 한 문장 평균 %d자요 (46자 아래로)" % avg)
    clear = s_len + has_src + s_cnt + s_sent

    # ── ⑤ 쉬움 — 어려운 말을 풀어 주는가 ───────────────────
    #
    # ★ 「이게 무슨 말이오」 상자는 **풀이로는 세고 비유로는 안 셉니다.**
    #
    #   `terms.picture_box` 는 그 컷에서 처음 나온 말의 그림을 한 상자로
    #   묶어 컷 밑에 답니다. 그런데 자는 그 상자를 통째로 걷어내고
    #   재고 있었습니다 — 말을 풀어 놓고도 「풀이 없이 지나가오」 가
    #   나왔습니다. 상자는 손님이 그 자리에서 읽는 글입니다.
    #
    #   다만 비유 점수는 여전히 **본문만** 봅니다. 상자를 달았다고
    #   본문이 그림이 되지는 않습니다 — 그러면 상자 하나로 스무 컷이
    #   전부 통과합니다.
    boxed = " ".join(GLS.findall(html or ""))
    used = [w for w in HARD if HARD_AT[w].search(text)]
    glossed = [w for w in used
               if HARD_GLOSSED[w].search(text) or ("<b>%s</b>" % w) in boxed]
    plain_s = round(100 * (1.0 if not used else _pct(len(glossed), len(used))))
    if used and plain_s < 60:
        miss.append("어려운 말이 풀이 없이 지나가오 — %s"
                    % " · ".join(w for w in used if w not in glossed)[:40])

    # ── ⑥ 비유 — 그림이 그려지는 한 줄이 있는가 ────────────
    #
    # ★ 전에는 쉬움 안에 25점으로 얹혀 있었고 **있으면 만점**이었습니다.
    #   그래서 스물두 컷짜리 리포트도 「셈이오」 한 번이면 통과였습니다.
    #   이제 분량을 봅니다 — 450자마다 하나가 만점입니다.
    #
    #   뜻풀이는 푼 게 아닙니다. 「식신 = 밖으로 내놓는 힘」 은 모르는
    #   말을 모르는 말로 바꾼 것입니다 (tools/plain_audit.py 와 같은 결).
    fig_hits = len(FIGURE.findall(text))
    figure = round(100 * _pct(fig_hits, max(1, n / 450)))
    if figure < 60:
        miss.append("비유가 모자라오 — 그림이 그려지는 한 줄을 다시오")

    # ── ⑦ 줄길이 — 한 줄이 눈에 편한가 ────────────────────
    #
    # ★ 손님이 시킨 것 (2026-09-03)
    #
    #   "폰트종류, 가독성, 폰트크기 등등 … 읽기속도랑 줄길이도 넣어줘"
    #
    # ★ 글이 아니라 **앉은 모양**을 봅니다
    #
    #   앞의 여섯 축은 무슨 말을 했는지를 봅니다. 이 축은 그 말이
    #   화면 폭에 어떻게 앉는지를 봅니다. 같은 문장도 한 줄에 마흔
    #   자로 앉으면 눈이 되돌아올 자리를 잃습니다.
    #
    #   화면 폭(396px)과 글자 크기는 `engine/typo.py` 가 압니다 —
    #   `tools/widow.py` 와 **같은 자**입니다.
    #
    #   세 가지를 셉니다
    #     한 줄     열넉~서른넉 자에 드는가
    #     과부 줄   문단 끝에 조각만 남지 않는가
    #     문단 키   한 문단이 일곱 줄을 안 넘는가
    # ★ 짧은 줄을 **아무 데서나 세면 안 됩니다.**
    #
    #   문단의 **마지막 줄은 원래 짧습니다** — 그게 정상입니다. 버튼
    #   글자·라벨·근거 딱지도 한 줄짜리라 짧습니다. 그걸 다 세면
    #   어느 화면이나 「조각 줄 스물다섯」 이 나오고, 그 숫자는
    #   고칠 데를 안 가리킵니다.
    #
    #   그래서 **문단 중간 줄**만 아래로 잽니다. 위로는(너무 긴 줄)
    #   모든 줄을 잽니다 — 긴 줄은 어디 있든 눈이 되돌아올 자리를
    #   잃습니다.
    paras = _typo.paragraphs(body)
    wrapped = [_typo.wrap(pg) for pg in paras]
    rows = [ln for w in wrapped for ln in w]
    if rows:
        def _w(ln):
            return sum(_typo.width_of(c) for c in ln)

        mid = [ln for w in wrapped for ln in w[:-1]]     # 마지막 줄 뺀 것
        long_ = sum(1 for ln in rows if _w(ln) > _typo.LINE_MAX)
        short_ = sum(1 for ln in mid if _w(ln) < _typo.LINE_MIN)
        bad = long_ + short_
        s_line = round(60 * max(0.0, 1.0 - bad / max(1, len(rows))))

        # ★ 과부 줄은 **여기서 안 셉니다.**
        #
        #   문단 끝에 「두었소.」 한 마디만 남는 것을 과부 줄이라 합니다.
        #   그런데 이 집은 그걸 이미 `text-wrap: pretty` 로 브라우저에
        #   맡겨 두었습니다 (overrides.css) — 브라우저가 마지막 줄을 보고
        #   앞줄에서 한 마디를 내려 줍니다.
        #
        #   그리고 화면에 박힌 글은 `tools/widow.py` 가 따로 셉니다.
        #   엔진이 조합하는 글은 조각 길이를 재도 조합된 결과가 어디서
        #   끊길지 모르므로 **일부러 안 셉니다** (tests/test_widow.py
        #   머리말). 여기서 세면 그 결정을 뒤집는 셈이고, 실제로
        #   본문 한 자리에서만 서른네 개가 잡혔습니다 — 전부 브라우저가
        #   고쳐 주는 것들입니다.
        #
        #   대신 그 몫을 **줄길이**에 얹습니다. 늑대가 안 왔는데 늑대라
        #   외치는 자는 곧 아무도 안 믿습니다.
        walls = sum(1 for w in wrapped if len(w) > _typo.PARA_MAX_LINES)
        s_wall = 40 if not walls else max(0, 40 - walls * 12)
        measure = s_line + s_wall
        if s_line < 36:
            miss.append("줄이 눈에 안 맞소 — 긴 줄 %d · 문단 중간의 "
                        "조각 줄 %d (한 줄 %d~%d 자)"
                        % (long_, short_, _typo.LINE_MIN, _typo.LINE_MAX))
        if walls:
            miss.append("한 문단이 %d줄을 넘는 자리가 %d 있소 — 벽으로 읽히오"
                        % (_typo.PARA_MAX_LINES, walls))
    else:
        measure = 0
        miss.append("잴 글이 없소")

    # ── ⑧ 읽기속도 — 몇 초짜리 화면인가 ──────────────────
    #
    # ★ 분량(명확)과 다릅니다
    #
    #   명확은 «할 말을 다 했는가» 를 봅니다. 이 축은 «한 번에 얼마나
    #   쏟는가» 를 봅니다. 같은 900자라도 한 덩이로 쏟으면 훑게 되고,
    #   끊어 놓으면 읽습니다. 이 집은 이미 한 컷씩 띄우기로 정해
    #   두었는데(`components/Reveal.tsx`) 그걸 재는 자가 없었습니다.
    #
    #   두 가지를 셉니다
    #     화면 길이     이 종류의 화면이 이만큼이면 오래 잡는가
    #     숨 쉴 자리    안 끊고 이어지는 가장 긴 덩이가 몇 초인가
    # ★ 접어 둔 말은 분량에서 뺍니다 (2026-09-03).
    #
    #   기본으로는 아무도 안 폅니다. 화면에 실제로 놓이는 글만 분량입니다.
    #   그 밖의 축(팩폭·울림·비유)에서는 그대로 셉니다 — 편 사람은 읽고,
    #   그 글이 이 집이 파는 것이기 때문입니다.
    # 읽는 데 걸리는 시간은 **점수에 안 씁니다** — 화면에 적어 주기만
    # 합니다. 길이는 죄가 아니오 (FILL_* 머리말 참고).
    secs = _typo.seconds(max(0, n - folded))
    # 가장 큰 상자가 한 화면의 몇 배인가.
    worst_box = max((len(_typo.wrap(b)) for b in _typo.boxes(html)), default=0)
    fill = worst_box / float(_typo.VIEW_LINES)
    s_total = round(60 * max(0.0, min(1.0,
                    (FILL_BAD - fill) / (FILL_BAD - FILL_OK))))
    longest = max((_typo.seconds(len(pg)) for pg in paras), default=0.0)
    s_breath = round(40 * max(0.0, min(1.0,
                    (BREATH_MAX * 2 - longest) / BREATH_MAX)))
    pace = s_total + s_breath
    if s_total < 36:
        miss.append("한 상자가 화면을 넘소 — %d줄이오 (한 화면 %d줄). "
                    "지우지 말고 상자를 가르시오"
                    % (worst_box, _typo.VIEW_LINES))
    if s_breath < 24:
        miss.append("숨 쉴 자리가 없소 — 안 끊고 %d초를 이어 가오 "
                    "(%d초 아래로 끊으시오)" % (round(longest), BREATH_MAX))

    # ── ⑨ 강조 — 어디부터 보라고 정해 주는가 ───────────────
    #
    #   **화면이 제 손으로 쓴 글**에서만 셉니다 (MARK_* 머리말 참고).
    #   `own` 은 엔진 글을 끼우기 **전**의 화면 글 길이입니다.
    marks = int(marks or 0)
    own_n = int(own or 0) or n
    per = marks / max(1.0, own_n / MARK_PER)
    if per < MARK_LOW:
        mark = round(100 * (per / MARK_LOW))
        miss.append("짚어 주는 데가 없소 — 화면 제 글 %d자에 굵은 글씨 "
                    "%d군데요" % (own_n, marks))
    elif per <= MARK_OK:
        mark = 100
    else:
        mark = round(100 * max(0.0, (MARK_HIGH - per) / (MARK_HIGH - MARK_OK)))
        miss.append("강조가 너무 많소 — 화면 제 글 %d자에 굵은 글씨 "
                    "%d군데요(200자당 %.1f). 다 굵으면 아무것도 안 굵소"
                    % (own_n, marks, per))

    total = round((pull + bite + heart + clear + plain_s + figure
                   + measure + pace + mark) / 9)
    return {
        "id": sid, "title": title, "kind": kind, "chars": n,
        "pull": pull, "bite": bite, "heart": heart,
        "clear": clear, "plain": plain_s, "figure": figure,
        "measure": measure, "pace": pace, "mark": mark,
        "secs": round(secs),
        "total": total,
        "actout": kinds,
        "missing": miss,
    }


def grade(total: int) -> str:
    """점수를 사람 말로. 붉은 것이 뭔지 한눈에 보여야 고칩니다."""
    if total >= 80:
        return "좋소"
    if total >= 65:
        return "쓸 만하오"
    if total >= 50:
        return "모자라오"
    return "고쳐야 하오"
