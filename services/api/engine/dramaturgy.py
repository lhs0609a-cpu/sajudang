ASK = re.compile(r"[?？]")
COLD_BAD = re.compile(r"이란|이라 하오|말합니다|뜻이오|뜻입니다|설명|"
                      r"보는 법|이라고 하")


def _cold_open(lines: list) -> bool:
    """첫 두 줄 중 하나가 지문이거나 물음이면 연 것입니다."""
    for s in lines[:2]:
        s = s.strip()
        if not s or COLD_BAD.search(s):
            continue
        if ASK.search(s) or NARR.search(s):
            return True
    return False


